"""Full-scale, brandless take-apart shears; original compound convex meshes."""
from dataclasses import dataclass
from functools import lru_cache
import math
import numpy as np

STEEL=(.64,.68,.71)
HANDLE=(.12,.24,.29)
TRAY_COLOR=(.82,.86,.85)
PIVOT_XY=np.array([.255,0.])
TRAY_XY=np.array([.475,0.])
TRAY_SIZE=np.array([.270,.260,.024])
WALL=.003
FLOOR=.003
START_ANGLES=np.radians([30.,-30.])
HEAD_XY=np.array([.012,.006])
SLOT_XY=np.array([.0068,.0128])
STEM_RADIUS=.003
PLATE_BOTTOM=(.006,.0094)
PLATE_THICK=.003
HEAD_BOTTOM=.0128
HEAD_TOP=.0148
BLADE=np.array([[.009,-.009],[.019,-.013],[.072,-.006],
                [.084,-.002],[.086,.001],[.080,.005],[.020,.012],[.009,.009]])

@dataclass(frozen=True)
class Solid:
    vertices: np.ndarray
    triangles: np.ndarray
    color: tuple
    kind: str

def rz(theta):
    c,s=math.cos(theta),math.sin(theta)
    return np.array([[c,-s,0],[s,c,0],[0,0,1.]])

def world(points,pos,rot): return np.asarray(points)@np.asarray(rot).T+np.asarray(pos)

def prism(polygon,z0,z1,color=STEEL,kind='metal'):
    poly=np.asarray(polygon,dtype=float)
    area=np.sum(poly[:,0]*np.roll(poly[:,1],-1)-poly[:,1]*np.roll(poly[:,0],-1))
    if area<0: poly=poly[::-1]
    n=len(poly); v=np.vstack((np.c_[poly,np.full(n,z0)],np.c_[poly,np.full(n,z1)]))
    tris=[]
    for i in range(n):
        j=(i+1)%n; tris.extend(((i,j,n+j),(i,n+j,n+i)))
    for i in range(1,n-1): tris.extend(((0,i+1,i),(n,n+i,n+i+1)))
    return Solid(v,np.asarray(tris,dtype=int),color,kind)

def box(center,size,color=STEEL,kind='metal'):
    x,y,z=np.asarray(center); a,b,c=np.asarray(size)/2
    return prism([[x-a,y-b],[x+a,y-b],[x+a,y+b],[x-a,y+b]],z-c,z+c,color,kind)

def circle(radius,n=48):
    t=np.arange(n)*2*math.pi/n
    return np.c_[radius*np.cos(t),radius*np.sin(t)]

def handle_center(i): return np.array([-.082,(-1 if i==0 else 1)*.019])
def grasp(i): return np.array([-.110,handle_center(i)[1],.006])

def handle_ring(i):
    c=handle_center(i); t=np.linspace(0,2*math.pi,49)
    out=c+np.c_[.032*np.cos(t),.022*np.sin(t)]
    ins=c+np.c_[.024*np.cos(t),.014*np.sin(t)]
    return [prism([out[j],out[j+1],ins[j+1],ins[j]],0,.012,HANDLE,'handle') for j in range(48)]

def slot_ring():
    # Rays include every rectangular corner, so the hole is genuinely rectangular
    # rather than a tessellation that accidentally blocks the matching head.
    corner=math.atan2(SLOT_XY[1],SLOT_XY[0])
    ts=np.unique(np.r_[np.linspace(0,2*math.pi,65),corner,math.pi-corner,math.pi+corner,2*math.pi-corner])
    dirs=np.c_[np.cos(ts),np.sin(ts)]
    radius=np.min(np.divide(SLOT_XY/2,np.abs(dirs),out=np.full_like(dirs,np.inf),where=np.abs(dirs)>1e-12),axis=1)
    inside=dirs*radius[:,None]; outside=.012*dirs
    return [prism([outside[j],outside[j+1],inside[j+1],inside[j]],PLATE_BOTTOM[1],PLATE_BOTTOM[1]+PLATE_THICK,kind='pivot') for j in range(len(ts)-1)]

def head_polygon():
    # 12 x 6mm elongated stem head with 0.8mm corner chamfers.
    x,y=HEAD_XY/2; c=.0008
    return np.array([[-x+c,-y],[x-c,-y],[x,-y+c],[x,y-c],
                     [x-c,y],[-x+c,y],[-x,y-c],[-x,-y+c]])

@lru_cache(None)
def half(i):
    z0=PLATE_BOTTOM[i]; sign=-1 if i==0 else 1
    blade=BLADE.copy(); blade[:,1]*=sign
    solids=[prism(blade,z0,z0+PLATE_THICK,kind='blade')]
    # Forged tang links the pivot to the molded loop without crossing the bearing.
    tang=np.array([[-.010,-.007],[-.010,.007],[-.058,sign*.019+.008],[-.058,sign*.019-.008]])
    # Convex ordering is generated by angle around the centroid.
    center=tang.mean(0); tang=tang[np.argsort(np.arctan2(*(tang-center)[:,::-1].T))]
    solids.append(prism(tang,z0,z0+PLATE_THICK,HANDLE,'handle'))
    solids+=handle_ring(i)
    if i==0:
        solids += [prism(circle(.012),z0,z0+PLATE_THICK,kind='pivot'),
                   prism(circle(STEM_RADIUS),z0+PLATE_THICK,HEAD_BOTTOM,kind='stem'),
                   prism(head_polygon(),HEAD_BOTTOM,HEAD_TOP,kind='head')]
    else: solids+=slot_ring()
    return tuple(solids)

@lru_cache(None)
def tray():
    x,y,z=TRAY_SIZE
    return (box([0,0,FLOOR/2],[x,y,FLOOR],TRAY_COLOR,'tray'),
            box([0,-(y-WALL)/2,z/2],[x,WALL,z],TRAY_COLOR,'tray'),
            box([0,(y-WALL)/2,z/2],[x,WALL,z],TRAY_COLOR,'tray'),
            box([-(x-WALL)/2,0,z/2],[WALL,y,z],TRAY_COLOR,'tray'),
            box([(x-WALL)/2,0,z/2],[WALL,y,z],TRAY_COLOR,'tray'))

@lru_cache(None)
def vertices(i): return np.concatenate([s.vertices for s in (half(i) if i<2 else tray())])

def head_fits(relative_angle,clearance=0.):
    # Head measured in upper-half coordinates; matching orientation is +/-90deg.
    p=head_polygon()@rz(relative_angle)[:2,:2].T
    return bool(np.all(np.abs(p)<=SLOT_XY/2-clearance))

def point_prism_distance(points,polygon,z0,z1):
    """Exact Euclidean distance to a convex XY extrusion, zero inside."""
    p=np.asarray(points); poly=np.asarray(polygon)
    signed=np.sum(poly[:,0]*np.roll(poly[:,1],-1)-poly[:,1]*np.roll(poly[:,0],-1))
    if signed<0: poly=poly[::-1]
    a=poly[None,:,:]; edge=np.roll(poly,-1,axis=0)-poly
    d=p[:,None,:2]-a
    cross=edge[None,:,0]*d[:,:,1]-edge[None,:,1]*d[:,:,0]
    inside=np.all(cross>=-1e-12,axis=1)
    t=np.clip((d*edge).sum(-1)/(edge*edge).sum(-1),0,1)
    xy=np.linalg.norm(d-t[...,None]*edge,axis=-1).min(1)
    xy=np.where(inside,0.,xy)
    z=np.maximum(np.maximum(z0-p[:,2],p[:,2]-z1),0.)
    return np.sqrt(xy*xy+z*z)

def blade_distance(points,pos,rot,i):
    p=(np.asarray(points)-pos)@rot
    poly=BLADE.copy(); poly[:,1]*=(-1 if i==0 else 1)
    return point_prism_distance(p,poly,PLATE_BOTTOM[i],PLATE_BOTTOM[i]+PLATE_THICK)

@lru_cache(None)
def metal_prisms(i):
    return tuple((s.vertices[:len(s.vertices)//2,:2],float(s.vertices[:,2].min()),float(s.vertices[:,2].max()))
                 for s in half(i) if s.kind!='handle')

def metal_distance(points,pos,rot,i):
    p=(np.asarray(points)-pos)@rot
    return np.min([point_prism_distance(p,poly,z0,z1) for poly,z0,z1 in metal_prisms(i)],axis=0)

def bbox_distance(points,pos,rot,verts):
    p=(np.asarray(points)-pos)@rot
    lo,hi=verts.min(0),verts.max(0)
    delta=np.maximum(np.maximum(lo-p,p-hi),0.)
    return np.linalg.norm(delta,axis=-1)
