from yam_arena import constants as _C  # noqa: E402

CAM = np.array(station.top_camera("calibrated").pos, float)  # the task's own top camera
GRIP_R = abs(float(_C.FINGER_OPEN))  # declared approximation of a hand's half-width (finger-pad half spacing)
GRIP_LEN = float(_C.TCP_OFFSET[2])  # declared approximation of the gripper body: tool point up 134 mm (link-frame offset)


def _seg_dist(p0, p1, q0, q1):
    """Exact smallest distance between segments p0-p1 and q0-q1 (closest-point algorithm for two segments)."""
    d1, d2, r = p1 - p0, q1 - q0, p0 - q0
    a, e, f = float(d1 @ d1), float(d2 @ d2), float(d2 @ r)
    eps = 1e-12
    if a <= eps and e <= eps:
        return float(np.linalg.norm(r))
    if a <= eps:
        s_, t_ = 0.0, min(max(f / e, 0.0), 1.0)
    else:
        c = float(d1 @ r)
        if e <= eps:
            t_, s_ = 0.0, min(max(-c / a, 0.0), 1.0)
        else:
            b = float(d1 @ d2)
            den = a * e - b * b
            s_ = min(max((b * f - c * e) / den, 0.0), 1.0) if den > eps else 0.0
            t_ = (b * s_ + f) / e
            if t_ < 0.0:
                t_, s_ = 0.0, min(max(-c / a, 0.0), 1.0)
            elif t_ > 1.0:
                t_, s_ = 1.0, min(max((b - c) / a, 0.0), 1.0)
    return float(np.linalg.norm((p0 + d1 * s_) - (q0 + d2 * t_)))


def _scored_points(state):
    """Centres of the 26 cuff segments of a (wrapped) cuff state: the cuff, its arrow segment and its closure."""
    return [np.asarray(c, float) for c, _ in t.segments(state.pos, state.quat_xyzw, state.joints)]


def _occluded(tcps, state):
    """Proximity proxy, NOT a render check: True if any camera-to-segment ray passes within GRIP_R of a hand, where a hand
    is a vertical capsule (tool point up GRIP_LEN). It does not test the camera frustum, the arm or wrist, gripper
    self-occlusion or rendered visibility; the capsule is a declared approximation, not the official hand geometry."""
    for tcp in tcps:
        q0 = np.asarray(tcp, float)
        q1 = q0 + np.array([0.0, 0.0, GRIP_LEN])
        for pt in _scored_points(state):
            if _seg_dist(CAM, pt, q0, q1) <= GRIP_R:
                return True
    return False


def _demo_final_tcps():
    d = t.demo()
    return tuple(tuple(float(v) for v in d[side][-1].pos) for side in ("left", "right"))


def test_seg_dist_exact():
    z = np.zeros(3)
    assert _seg_dist(z, np.array([1.0, 0, 0]), np.array([0.5, 0.2, 0]), np.array([0.5, 1.0, 0])) == pytest.approx(0.2)
    assert _seg_dist(z, np.array([1.0, 0, 0]), np.array([2.0, 0, 0]), np.array([3.0, 0, 0])) == pytest.approx(1.0)


def test_occlusion_proxy_rays_to_the_cuff_clear_of_hands_at_the_end():
    """Proximity proxy: at the end of the scripted demo none of the 26 rays from the top camera to the cuff segments
    passes within a hand capsule's radius of either parked hand. Not tested: camera frustum, arm and wrist, gripper
    self-occlusion, rendered visibility."""
    assert not _occluded(_demo_final_tcps(), wrap())


def test_occlusion_proxy_negative_control_hand_on_a_ray():
    """The proxy can fail: a hand placed on a ray to the arrow segment or to a cuff end counts as occluding, and so does
    a hand at the closure-press pose."""
    cu = wrap()
    pts = _scored_points(cu)
    for pt in (pts[t.MARK_SEG], pts[0], pts[-1]):
        on_ray = CAM + 0.8 * (pt - CAM)
        assert _occluded((tuple(on_ray), _demo_final_tcps()[1]), cu)
    assert _occluded(((t.CUFF_X, 0.040, t.TOP + 0.145 + t.PAD_TIP_PAST_TCP), _demo_final_tcps()[1]), cu)


