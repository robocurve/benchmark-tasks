"""Offline tests for bp-cuff-apply (CPU only; official yam_arena runtime on the path, no simulator).

Cuff states are generated by code: an ideal wrap round the arm (every hinge bent by the same angle so the chain follows a circle
just outside the skin) placed so the artery arrow sits on the artery line, then perturbed. Covers: the score table (every value
the scorer can return is documented in task.json), the closure's overlap measure, the listed shortcuts scoring 0, the scoring-text
numbers in the scorer, demo reach and purity.
"""
import json
import math
import pathlib
import re
import sys

import numpy as np
import pytest

HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import bp_cuff_apply as t  # noqa: E402
from labkit import PartState  # noqa: E402
from yam_arena import station  # noqa: E402
from yam_arena.demo import ArmPlan  # noqa: E402

PARK = [np.array([0.16, 0.32, t.TOP + 0.20]), np.array([0.16, -0.32, t.TOP + 0.20])]


def quat_x(a):
    return np.array([math.sin(a / 2), 0.0, 0.0, math.cos(a / 2)])


def cuff(pos, alpha=0.0, joints=None):
    pos = np.asarray(pos, float)
    return PartState(pos=pos, quat_xyzw=quat_x(alpha), lin_vel=np.zeros(3), ang_vel=np.zeros(3),
                     low=pos - 0.3, high=pos + 0.3, joints=joints or {f"s{i:02d}": 0.0 for i in range(t.N_SEG) if i != t.ROOT})


def wrap(dx=0.0, dtheta=0.0, lift=0.0):
    """Ideal one-and-a-half-turn wrap: root segment tangent at radius rho, every hinge bent by SEG / rho (inward)."""
    rho = t.contact_radius() + t.TH / 2 + 0.0005 + lift
    d = t.SEG / rho
    th_r = -(t.MARK_SEG - t.ROOT) * d + dtheta  # arrow segment on the top (theta 0)
    pos = (t.CUFF_X + dx, rho * math.sin(th_r), t.AX + rho * math.cos(th_r))
    joints = {f"s{i:02d}": t.sign(i) * d for i in range(t.N_SEG) if i != t.ROOT}
    return cuff(pos, math.pi - th_r, joints)


def flat(dx=0.0, dy=0.0, dz=0.0):
    st = t.CUFF.pos if hasattr(t.CUFF, "pos") else (t.CUFF_X, 0.0, t.TOP + t.TH / 2 + 0.0005)
    joints = {f"s{i:02d}": t.rest_angle(i) for i in range(t.N_SEG) if i != t.ROOT}
    return cuff((st[0] + dx, st[1] + dy, st[2] + dz), 0.0, joints)


def sc(state, engaged=False, pads=PARK):
    t._EP.update(t._fresh())
    t._EP.update({"engaged": engaged, "pads": list(pads), "tcps": list(pads)})
    return t.score({"cuff": state})


def documented_scores():
    tj = json.loads((HERE / "task.json").read_text())
    return {float(v) for v in re.findall(r"(?<![\d.])(\d\.\d+|[01])(?![\d.])", tj["scoring"].split("Judged")[1])} & {0.0, 0.3, 0.6, 1.0}


# -- the constructed states are what they claim ----------------------------------------------------------------------

def test_ideal_wrap_is_snug_one_turn_and_arrow_on_the_line():
    k = t.components(wrap())
    assert k["turn"] and k["max_gap"] <= 0.003
    assert k["mark_out"] and k["mark_arc"] <= 0.002
    assert t.EDGE_ABOVE[0] <= k["edge_above"] <= t.EDGE_ABOVE[1]


def test_overlap_measure_sees_the_closure_and_a_lifted_loop():
    on, lift = t.overlap(t.segments(wrap().pos, wrap().quat_xyzw, wrap().joints))
    assert on >= t.ENGAGE_OVERLAP and abs(lift) <= t.ENGAGE_GAP
    st = wrap()
    j = dict(st.joints)
    for i in range(t.N_SEG - t.N_LOOP, t.N_SEG):  # peel the loop end up off the hook face
        j[f"s{i:02d}"] = t.sign(i) * -0.15
    on2, _ = t.overlap(t.segments(st.pos, st.quat_xyzw, j))
    assert on2 < t.ENGAGE_OVERLAP


def _loop_face_point(segs, i, out=0.002):
    """A point ``out`` metres outside the outer face of segment i."""
    c, R = segs[i]
    return c + R @ np.array([0.0, 0.0, -(t.TH / 2 + out)])


def test_engage_gate():
    st = wrap()
    segs = t.segments(st.pos, st.quat_xyzw, st.joints)
    i = t.N_SEG - 2  # a lying loop segment
    on = _loop_face_point(segs, i)
    far = _loop_face_point(segs, i, out=0.010)
    assert t.engages(segs, [on, PARK[1]], (True, False))  # closed fist on 60+ mm of lying overlap
    assert not t.engages(segs, [on, PARK[1]], (False, False))  # fingers open on it (a pinch reads open)
    assert not t.engages(segs, [far, PARK[1]], (True, False))  # closed fist 10 mm away
    j = dict(st.joints)
    for k in range(t.N_SEG - t.N_LOOP, t.N_SEG - 2):  # peel all but the last two loop segments: one 20 mm segment left lying
        j[f"s{k:02d}"] = t.sign(k) * -0.25
    segs2 = t.segments(st.pos, st.quat_xyzw, j)
    lying = [k for k, g in t.loop_gaps(segs2).items() if abs(g) <= t.ENGAGE_GAP]
    assert lying and t.SEG * len(lying) < t.ENGAGE_OVERLAP
    assert not t.engages(segs2, [_loop_face_point(segs2, lying[0]), PARK[1]], (True, False))  # closed fist on it, overlap too short


# -- score table -------------------------------------------------------------------------------------------------------

def test_full_credit():
    assert sc(wrap(), engaged=True) == 1.0


def test_tiers():
    assert sc(wrap(), engaged=False) == 0.3  # one snug turn, not closed
    assert sc(wrap(dtheta=0.025 / 0.054), engaged=True) == 0.6  # arrow 25 mm off the line
    assert sc(wrap(dx=-0.025), engaged=True) == 0.6  # lower edge 45 mm above the crease
    near = [np.array([t.CUFF_X, 0.0, t.AX + 0.075]), PARK[1]]
    assert sc(wrap(), engaged=True, pads=near) == 0.6  # a gripper 2 cm off the cuff
    assert sc(wrap(lift=0.02), engaged=True) == 0.3  # 20 mm off the skin: not snug, still one turn within 30 mm
    assert sc(wrap(lift=0.04), engaged=True) == 0.0  # 40 mm off


def test_every_returned_value_is_documented():
    got = {sc(wrap(), True), sc(wrap(), False), sc(wrap(dx=-0.025), True), sc(flat())}
    assert got <= documented_scores() and got == {0.0, 0.3, 0.6, 1.0}


