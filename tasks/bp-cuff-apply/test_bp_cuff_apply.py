def _loop_face_point(segs, i, out=0.002):
    """A point ``out`` metres outside the outer face of segment i."""
    c, R = segs[i]
    return c + R @ np.array([0.0, 0.0, -(t.TH / 2 + out)])


def test_engage_gate():
    st = wrap()
    segs = t.segments(st.pos, st.quat_xyzw, st.joints)
    i = t.N_SEG - 2  # a lying loop segment
    on = _loop_face_point(segs, i, out=0.0005)  # pad ON the face (within 2 mm)
    far = _loop_face_point(segs, i, out=0.010)
    assert t.engages(segs, [on, PARK[1]], (True, False))  # closed fist on 60+ mm of lying overlap
    assert not t.engages(segs, [on, PARK[1]], (False, False))  # fingers open on it (a pinch reads open)
    assert not t.engages(segs, [far, PARK[1]], (True, False))  # closed fist 10 mm away
    j = dict(st.joints)
    for k in range(t.N_SEG - t.N_LOOP, t.N_SEG - 2):  # peel all but the last two loop segments: one 20 mm segment left lying
        j[f"s{k:02d}"] = t.sign(k) * -0.25
    segs2 = t.segments(st.pos, st.quat_xyzw, j)
    lying = [k for k, g in t.loop_gaps(segs2).items() if abs(g) <= t.ENGAGE_GAP]
    assert lying and t.SEG * len(lying) < t.ENGAGE_OVERLAP
    assert not t.engages(segs2, [_loop_face_point(segs2, lying[0]), PARK[1]], (True, False))  # closed fist on it, overlap too short


