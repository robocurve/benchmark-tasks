def pixels(word):
    return {(4*i+c, r) for i, ch in enumerate(word) for r, row in enumerate(ROWS[ch].split()) for c, v in enumerate(row) if v == '1'}

def label(word, x, y, z, pitch, color):
    width = (4*len(word)-1)*pitch
    return [((x-width/2+(c+.5)*pitch,y+(2-r)*pitch,z),(pitch*.83,pitch*.83,.0006),color) for c,r in pixels(word)]
