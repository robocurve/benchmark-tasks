@dataclass(frozen=True)
class Plastic:
    """Bend joints that take a permanent set, as solid copper house wire or a steel coat hanger does.

    Every bend axis of every joint is a position drive (``stiffness`` N m/rad, ``damping`` N m s/rad) toward a target,
    the joint's set. After every control step (a mechkit on_step hook, 20 Hz) the kit compares each joint's bend
    (rotY, rotZ as a 2-vector) with its set: while the elastic part (bend minus set) stays within ``yield_angle``
    (rad) nothing changes, so a small load bends the wire and it springs back; past it, the set moves along so the
    elastic part is exactly ``yield_angle`` (``plastic_update``), so a large bend stays bent, less a springback of
    ``yield_angle`` per joint. This is elastic, perfectly plastic bending: no strain hardening and no Bauschinger
    effect.

    Why it does not creep, where a joint hold does (GEOMETRY.md, smoke runs 2026-11-12): a hold is velocity-level
    Coulomb friction with no memory of position, so a steady load leaks through it a little every step. A drive is a
    spring to a fixed target: under a steady load the joint settles at load / stiffness from its set and stays there,
    as the sprung detent slide did (no measurable drift). The set only moves when the load exceeds stiffness x
    yield_angle (the yield moment), which is real yielding, not creep. ``max_elastic_overhang(rope)`` gives the
    longest free length a joint can carry against gravity and stay elastic.

    ``from_wire`` derives the numbers from beam theory for one joint of ``segment`` length: stiffness = E I / segment,
    yield_angle = segment x 2 sigma_y / (E d), damping = stiffness x 2 ms. ``copper_12awg`` and ``coat_hanger`` are
    the defaults. Plastic replaces the rope's ``bend_stiffness`` and ``bend_damping``."""

    yield_angle: float
    stiffness: float
    damping: float
    segment: float | None = None  # the joint spacing the numbers were made for, or None
    label: str = ""

    def __post_init__(self) -> None:
        object.__setattr__(self, "yield_angle", _num("plastic yield_angle", self.yield_angle, 0.0, low_open=True))
        object.__setattr__(self, "stiffness", _num("plastic stiffness", self.stiffness, 0.0, low_open=True))
        object.__setattr__(self, "damping", _num("plastic damping", self.damping, 0.0))
        if self.segment is not None:
            object.__setattr__(self, "segment", _num("plastic segment", self.segment, 0.0, low_open=True))

    @property
    def yield_moment(self) -> float:
        """Bending moment (N m) at which a joint starts to take a set."""
        return float(self.stiffness * self.yield_angle)

    @classmethod
    def from_wire(cls, diameter: float, modulus: float, yield_stress: float, segment: float = SEGMENT,
                  label: str = "") -> "Plastic":
        """Round solid wire of ``diameter`` (m), Young's ``modulus`` (Pa) and ``yield_stress`` (Pa), jointed every
        ``segment`` (m): stiffness E I / segment with I = pi d^4 / 64, yield angle segment x 2 sigma_y / (E d)."""
        d = _num("wire diameter", diameter, 0.0, low_open=True)
        E = _num("wire modulus", modulus, 0.0, low_open=True)
        sy = _num("wire yield_stress", yield_stress, 0.0, low_open=True)
        L = _num("wire segment", segment, 0.0, low_open=True)
        k = E * math.pi * d ** 4 / 64 / L
        return cls(float(L * 2 * sy / (E * d)), float(k), float(k * DAMP_TIME), float(L), label)


def copper_12awg(segment: float = SEGMENT) -> Plastic:
    """12 AWG solid annealed copper building wire (2.053 mm conductor, E 117 GPa, yield 70 MPa; the insulation's
    stiffness is left out). At 2 cm joints: 5.1 N m/rad, yield 0.67 deg, yield moment 0.060 N m."""
    return Plastic.from_wire(0.002053, 117e9, 70e6, segment, "12 AWG solid copper")


def coat_hanger(segment: float = SEGMENT) -> Plastic:
    """A wire coat hanger: 2.3 mm (13 gauge) low carbon steel, E 200 GPa, yield 450 MPa. At 2 cm joints: 13.7 N m/rad,
    yield 2.2 deg, yield moment 0.54 N m."""
    return Plastic.from_wire(0.0023, 200e9, 450e6, segment, "steel coat hanger")


def plastic_update(bend, target, yield_angle: float, limit: float | None = None) -> np.ndarray:
    """The set update rule, pure. ``bend`` and ``target`` are arrays of the same shape whose last axis is one joint's
    bend vector (rad; length 2 for rotY, rotZ, or 1 per axis). Where the elastic part, |bend - target|, exceeds
    ``yield_angle`` the target moves toward the bend until the elastic part is exactly ``yield_angle``, along the same
    direction; elsewhere it is unchanged. ``limit`` clips the result to +-limit (the joint's max_bend)."""
    b = np.asarray(bend, dtype=float)
    t = np.asarray(target, dtype=float)
    if b.shape != t.shape or b.ndim == 0:
        raise ValueError(f"plastic_update: bend {b.shape} and target {t.shape} must have the same shape")
    y = _num("yield_angle", yield_angle, 0.0, low_open=True)
    off = b - t
    mag = np.linalg.norm(off, axis=-1, keepdims=True)
    over = mag > y
    scale = np.where(over, y / np.where(over, mag, 1.0), 1.0)
    out = np.where(over, b - off * scale, t)
    if limit is not None:
        lim = _num("limit", limit, 0.0, low_open=True)
        out = np.clip(out, -lim, lim)
    return out


# -- the rope ----------------------------------------------------------------------------------------------------------


@dataclass(frozen=True)
class Rope(Box):
    """A rope laid along ``path`` (polyline of (x, y, z) rope-axis points, metres, world frame). Subclasses Box only so
    task files accept it; ``pos`` and ``size`` are filled in as its bounding box. ``mass`` must stay None: give
    ``rope_mass`` (kg, the rope without end bodies). A rope is never jittered by yam_arena (``free`` is False).

    ``length`` defaults to the path length; ``segment`` is the target segment length (the real one is length / n).
    ``bend_stiffness`` (N m/rad per bend axis per joint) pulls toward the laid shape; ``max_bend`` (rad) limits each
    joint either side of it. ``collision_sides`` 3 to 16 gives an n-sided prism collider with a flat down (0: round
    capsule, which rolls). ``anchor_start`` welds the start (its end body, if any) to the world.

    ``fixtures`` (Fixture) are bodies welded partway along it, ``sliders`` (Slider) bodies threaded on it (add
    ``slider_objects()`` to OBJECTS), and ``plastic`` (Plastic) makes the joints take a permanent set; it replaces
    ``bend_stiffness`` and ``bend_damping``."""

    pos: tuple[float, float, float] = (0.0, 0.0, 0.0)
    color: tuple[float, float, float] = (0.95, 0.45, 0.10)
    path: tuple = ()
    length: float | None = None
    segment: float = SEGMENT
    radius: float = 0.004
    rope_mass: float = 0.03
    bend_stiffness: float = 0.01
    bend_damping: float = 0.002
    armature: float = 5e-6
    max_bend: float = 1.2
    friction: float = 0.8
    collision_sides: int = 8
    anchor_start: bool = False
    self_collision: bool = True
    start_body: EndBody | None = None
    end_body: EndBody | None = None
    fixtures: tuple = ()
    sliders: tuple = ()
    plastic: Plastic | None = None
    layout: Layout | None = field(default=None, compare=False, repr=False)

    def __post_init__(self) -> None:
        if self.mass is not None:
            raise ValueError(f"rope {self.name}: give rope_mass, not mass (mass must stay None)")
        r = _num(f"rope {self.name}: radius", self.radius, MIN_RADIUS)
        _num(f"rope {self.name}: rope_mass", self.rope_mass, 0.0, low_open=True)
        _num(f"rope {self.name}: bend_stiffness", self.bend_stiffness, 0.0)
        _num(f"rope {self.name}: bend_damping", self.bend_damping, 0.0)
        _num(f"rope {self.name}: armature", self.armature, 0.0)
        _num(f"rope {self.name}: friction", self.friction, 0.0)
        mb = _num(f"rope {self.name}: max_bend", self.max_bend, 0.0, 1.5, low_open=True)
        sides = self.collision_sides
        if isinstance(sides, bool) or not isinstance(sides, int) or not (sides == 0 or 3 <= sides <= MAX_PRISM_SIDES):
            raise ValueError(f"rope {self.name}: collision_sides must be 0 or an integer 3 to {MAX_PRISM_SIDES}, "
                             f"got {sides!r}")
        for flag in ("anchor_start", "self_collision"):
            if not isinstance(getattr(self, flag), bool):
                raise ValueError(f"rope {self.name}: {flag} must be True or False")
        for end in ("start_body", "end_body"):
            b = getattr(self, end)
            if b is not None and not isinstance(b, EndBody):
                raise ValueError(f"rope {self.name}: {end} must be an EndBody or None, got {type(b).__name__}")
        path = _path(self.path)
        object.__setattr__(self, "path", _pts(path))
        lay = segment_layout(path, self.segment, self.length)
        if lay.seg_len <= 2 * r:
            raise ValueError(f"rope {self.name}: segment length {lay.seg_len:.4f} m must exceed the diameter "
                             f"{2 * r:.4f} m")
        for jf in joint_frames(lay):
            if jf.bend > mb + 1e-9:
                raise ValueError(f"rope {self.name}: the path bends {math.degrees(jf.bend):.1f} deg at joint "
                                 f"{jf.index}, over max_bend {math.degrees(mb):.1f} deg; round the corner or use "
                                 "shorter segments")
        gap, pair = _self_clearance(lay, r)
        if gap < -1e-9:
            raise ValueError(f"rope {self.name}: segments {pair} overlap by {-gap * 1000:.2f} mm as laid; widen the "
                             "U, raise the coil pitch, or lay it differently")
        object.__setattr__(self, "layout", lay)
        self._check_end_bodies()
        self._check_plastic(mb)
        self._check_fixtures()
        self._check_sliders()
        pts = self.collider_points()
        lo, hi = pts.min(0), pts.max(0)
        object.__setattr__(self, "pos", tuple(float(v) for v in (lo + hi) / 2))
        object.__setattr__(self, "size", tuple(float(v) for v in np.maximum(hi - lo, 1e-6)))
        self._check()

    # -- the laid pose (pure, plain floats where the simulator sees them) --------------------------------------------

    @property
    def free(self) -> bool:  # never jittered: yam_arena's reset writes rigid poses only
        return False

    @property
    def segments(self) -> int:
        return self.layout.n

    @property
    def seg_len(self) -> float:
        return self.layout.seg_len

    @property
    def total_length(self) -> float:
        """Nominal rope length (m) without end bodies: segments x segment length."""
        return self.layout.length

    def root_pose(self) -> tuple[tuple[float, float, float], tuple[float, float, float, float]]:
        """Segment 0's laid centre and (x, y, z, w) rotation, plain floats: the articulation's root pose."""
        return (_floats(self.layout.centres[0]), _xyzw(_matrix_quat(self.layout.rots[0])))

    def end_frame(self, end: str) -> tuple[np.ndarray, np.ndarray]:
        """(rotation, origin) of the laid end frame: origin at the tip, +x pointing away from the rope."""
        lay = self.layout
        if end == "start":
            return lay.rots[0] @ _quat_matrix(_FLIP), lay.knots[0].copy()
        if end == "end":
            return lay.rots[-1].copy(), lay.knots[-1].copy()
        raise ValueError(f"rope end must be 'start' or 'end', got {end!r}")

    def body(self, end: str) -> EndBody | None:
        if end not in ENDS:
            raise ValueError(f"rope end must be 'start' or 'end', got {end!r}")
        return self.start_body if end == "start" else self.end_body

    def grasp_point(self, end: str, local=(0.0, 0.0, 0.0)) -> tuple[float, float, float]:
        """Where a point given in an end frame (an end body's frame, or the bare tip's) starts, in the world, as plain
        floats: the fixed layout a demo may plan from without reading simulator state."""
        rot, origin = self.end_frame(end)
        return _floats(rot @ np.asarray(local, dtype=float) + origin)

    def collider_points(self) -> np.ndarray:
        """Bound points of every collider at the laid pose (segments as round bars, end bodies' shapes)."""
        lay, r = self.layout, self.radius
        ring_pts = np.array([(0.0, r * math.cos(a), r * math.sin(a)) for a in np.linspace(0, 2 * math.pi, 12,
                                                                                              endpoint=False)])
        pts = [ring_pts @ lay.rots[min(i, lay.n - 1)].T + k for i, k in enumerate(lay.knots)]
        for end in ENDS:
            b = self.body(end)
            if b is not None:
                rot, origin = self.end_frame(end)
                pts.append(b.points() @ rot.T + origin)
        for f in self.fixtures:
            rot, origin = self.fixture_frame(f.name)
            pts.append(f.body.points() @ rot.T + origin)
        return np.vstack(pts)

    def lowest(self) -> float:
        """Lowest collider z (m) at the laid pose: keep it at or just above the table top."""
        return float(self.collider_points()[:, 2].min())

    def body_poses(self) -> dict[str, tuple[tuple[float, ...], tuple[float, ...]]]:
        """Every body's laid pose relative to segment 0's frame, as the USD authors it: name -> ((x, y, z),
        (w, x, y, z)), plain floats."""
        lay = self.layout
        r0, c0 = lay.rots[0], lay.centres[0]
        out = {}
        for i in range(lay.n):
            out[f"seg_{i}"] = (_floats(r0.T @ (lay.centres[i] - c0)), _matrix_quat(r0.T @ lay.rots[i]))
        for end in ENDS:
            if self.body(end) is not None:
                rot, origin = self.end_frame(end)
                out[f"{end}_body"] = (_floats(r0.T @ (origin - c0)), _matrix_quat(r0.T @ rot))
        for f in self.fixtures:
            rot, origin = self.fixture_frame(f.name)
            out[f"fix_{f.name}"] = (_floats(r0.T @ (origin - c0)), _matrix_quat(r0.T @ rot))
        return out

    # -- fixtures, sliders and the plastic set (pure, plain floats where a demo sees them) ------------------------------

    def fixture(self, name: str) -> Fixture:
        for f in self.fixtures:
            if f.name == name:
                return f
        raise ValueError(f"rope {self.name}: no fixture {name!r} (fixtures: {[f.name for f in self.fixtures]})")

    def slider(self, name: str) -> Slider:
        for s in self.sliders:
            if s.name == name:
                return s
        raise ValueError(f"rope {self.name}: no slider {name!r} (sliders: {[s.name for s in self.sliders]})")

    def fixture_segment(self, name: str) -> int:
        """Index of the segment the fixture is welded to."""
        return _arc_frame(self.layout, self.fixture(name).at)[0]

    def fixture_frame(self, name: str) -> tuple[np.ndarray, np.ndarray]:
        """(rotation, origin) of the laid fixture frame: origin on the rope axis at its arclength, +x along the rope."""
        _, rot, origin = _arc_frame(self.layout, self.fixture(name).at)
        return rot, origin

    def fixture_point(self, name: str, local=(0.0, 0.0, 0.0)) -> tuple[float, float, float]:
        """Where a point in the fixture's frame starts, in the world, as plain floats (fixed layout, no state)."""
        rot, origin = self.fixture_frame(name)
        return _floats(rot @ np.asarray(local, dtype=float) + origin)

    def slider_frame(self, name: str) -> tuple[np.ndarray, np.ndarray]:
        """(rotation, origin) of the slider frame at its start: origin on the rope axis at ``at``, +x along the rope."""
        _, rot, origin = _arc_frame(self.layout, self.slider(name).at)
        return rot, origin

    def slider_point(self, name: str, local=(0.0, 0.0, 0.0)) -> tuple[float, float, float]:
        """Where a point in the slider's frame starts, in the world, as plain floats (fixed layout, no state)."""
        rot, origin = self.slider_frame(name)
        return _floats(rot @ np.asarray(local, dtype=float) + origin)

    def slider_objects(self) -> list[SliderMech]:
        """One rigid task object per slider, at its start pose, for OBJECTS: ``[ROPE, *ROPE.slider_objects()]``."""
        out = []
        for s in self.sliders:
            rot, origin = self.slider_frame(s.name)
            shapes = [_turn_shape(sh, rot, (0.0, 0.0, 0.0)) for sh in s.body.shapes]
            fr = self.friction if s.body.friction is None else s.body.friction
            out.append(SliderMech(s.name, pos=_floats(origin), mass=float(s.body.mass), color=_floats(self.color),
                                  shapes=tuple(shapes), friction=float(fr), rope=self.name, slider=s.name,
                                  frame_quat=_matrix_quat(rot)))
        return out

    def slider_clearance(self, name: str) -> float:
        """Radial clearance (m) of the slider's bore over the rope's collider corners."""
        return float(self.slider(name).bore - collider_radius(self.radius, self.collision_sides))

    def pass_bend(self, name: str) -> float:
        """Largest joint bend (rad) a straight slider rides over without its bore touching the rope: a kink at the
        slider's middle puts each leg (length / 2) tan(bend / 2) off its axis, so bend = 2 atan(2 clearance / length).
        Lead-in chamfers and the rope's give let it pass sharper bends under a pull; past this it starts to bind."""
        s = self.slider(name)
        return float(2 * math.atan2(2 * self.slider_clearance(name), max(s.length(), 1e-9)))

    def captive(self, name: str) -> dict[str, bool]:
        """For each end, whether it keeps the slider on: an end body with a collider reaching farther from the rope
        axis than the bore cannot pass through it. A bare end, or an anchored bare start, lets it off."""
        s = self.slider(name)
        out = {}
        for end in ENDS:
            b = self.body(end)
            if b is None:
                out[end] = False
                continue
            pts = np.vstack([mechkit.shape_points(sh) for sh in b.shapes if sh.collide])
            out[end] = bool(np.linalg.norm(pts[:, 1:], axis=1).max() > s.bore + 1e-9)
        return out

    def laid_rels(self) -> np.ndarray:
        """(n - 1, 3, 3) laid relative rotation of each joint (segment i - 1 to segment i)."""
        return np.array([_quat_matrix(jf.rot0) for jf in joint_frames(self.layout)]).reshape(-1, 3, 3)

    def set_polyline(self, set_bends=None) -> np.ndarray:
        """Knots (n + 1, 3) of the shape the rope takes with every joint at ``set_bends`` ((n - 1, 2) rad, the
        plastic set; zeros, the laid shape, by default) and segment 0 where it was laid."""
        lay = self.layout
        b = np.zeros((lay.n - 1, 2)) if set_bends is None else np.asarray(set_bends, dtype=float).reshape(lay.n - 1, -1)
        return _chain_knots(lay.rots[0], lay.centres[0], self.laid_rels(), b, lay.seg_len)

    def _seg_shape(self) -> Shape:
        """One segment's collider in the segment frame, for clearance checks."""
        if self.collision_sides:
            return segment_collider(self.layout.seg_len, self.radius, self.collision_sides)
        return mechkit.cyl((0.0, 0.0, 0.0), self.radius, self.layout.seg_len + 1.8 * self.radius, axis="x")

    def _clear_of_rope(self, what: str, body: EndBody, rot, origin, skip=()) -> None:
        """Raise when a body at (rot, origin) overlaps a segment not in ``skip``, an end body, or a fixture."""
        lay, seg = self.layout, self._seg_shape()
        reach = float(np.linalg.norm(body.points(), axis=1).max()) + lay.seg_len + 2 * self.radius + 0.01
        for sh in body.shapes:
            if not sh.collide:
                continue
            for j in range(lay.n):
                if j in skip or np.linalg.norm(lay.centres[j] - origin) > reach:
                    continue
                g = mechkit.gap(sh, (rot, origin), seg, (lay.rots[j], lay.centres[j]))
                if g < -1e-6:
                    raise ValueError(f"rope {self.name}: {what} overlaps segment {j} by {-g * 1000:.2f} mm as laid")
            for end in ENDS:
                b = self.body(end)
                if b is None:
                    continue
                re, oe = self.end_frame(end)
                for se in b.shapes:
                    if se.collide and mechkit.gap(sh, (rot, origin), se, (re, oe)) < -1e-6:
                        raise ValueError(f"rope {self.name}: {what} overlaps the {end} body as laid")

    def _check_plastic(self, max_bend: float) -> None:
        p = self.plastic
        if p is None:
            return
        if not isinstance(p, Plastic):
            raise ValueError(f"rope {self.name}: plastic must be a Plastic or None, got {type(p).__name__}")
        if p.yield_angle >= max_bend:
            raise ValueError(f"rope {self.name}: plastic yield_angle {p.yield_angle:.4f} rad must be under max_bend")
        object.__setattr__(self, "bend_stiffness", float(p.stiffness))
        object.__setattr__(self, "bend_damping", float(p.damping))

    def _check_fixtures(self) -> None:
        fx = tuple(self.fixtures)
        object.__setattr__(self, "fixtures", fx)
        for f in fx:
            if not isinstance(f, Fixture):
                raise ValueError(f"rope {self.name}: fixtures must be Fixtures, got {type(f).__name__}")
        names = [f.name for f in fx]
        if len(set(names)) != len(names):
            raise ValueError(f"rope {self.name}: fixture names repeat: {names}")
        for f in fx:
            if f.at > self.total_length + 1e-12:
                raise ValueError(f"rope {self.name}: fixture {f.name} at {f.at:.4f} m is past the rope's "
                                 f"{self.total_length:.4f} m")
            i = self.fixture_segment(f.name)
            skip = {i, i - 1, i + 1} if f.filter_neighbours else {i}
            rot, origin = self.fixture_frame(f.name)
            self._clear_of_rope(f"fixture {f.name}", f.body, rot, origin, skip)
        for a in range(len(fx)):
            for b in range(a + 1, len(fx)):
                ra, oa = self.fixture_frame(fx[a].name)
                rb, ob = self.fixture_frame(fx[b].name)
                for sa in fx[a].body.shapes:
                    for sb in fx[b].body.shapes:
                        if sa.collide and sb.collide and mechkit.gap(sa, (ra, oa), sb, (rb, ob)) < -1e-6:
                            raise ValueError(f"rope {self.name}: fixtures {fx[a].name} and {fx[b].name} overlap")

    def _check_sliders(self) -> None:
        sl = tuple(self.sliders)
        object.__setattr__(self, "sliders", sl)
        for s in sl:
            if not isinstance(s, Slider):
                raise ValueError(f"rope {self.name}: sliders must be Sliders, got {type(s).__name__}")
        names = [s.name for s in sl]
        if len(set(names)) != len(names) or self.name in names:
            raise ValueError(f"rope {self.name}: slider names must be distinct and not the rope's: {names}")
        for s in sl:
            if s.at > self.total_length + 1e-12:
                raise ValueError(f"rope {self.name}: slider {s.name} at {s.at:.4f} m is past the rope's "
                                 f"{self.total_length:.4f} m")
            c = self.slider_clearance(s.name)
            if c < MIN_SLIDER_CLEARANCE - 1e-9:
                raise ValueError(f"rope {self.name}: slider {s.name} bore {s.bore * 1000:.2f} mm clears the rope's "
                                 f"collider by {c * 1000:.2f} mm per side, under {MIN_SLIDER_CLEARANCE * 1000:.1f} mm; "
                                 "use slider_bore()")
            rot, origin = self.slider_frame(s.name)
            # the declared bore must be the body's: nothing inside it, something within 0.5 mm outside it
            length = max(s.length(), 1e-4)
            inner = mechkit.cyl((0.0, 0.0, 0.0), s.bore - 0.0002, length, axis="x")
            outer = mechkit.cyl((0.0, 0.0, 0.0), s.bore + 0.0005, length, axis="x")
            solid = [sh for sh in s.body.shapes if sh.collide]
            if any(mechkit.gap(sh, (rot, origin), inner, (rot, origin)) < 0.0 for sh in solid):
                raise ValueError(f"rope {self.name}: slider {s.name} reaches inside its declared bore "
                                 f"{s.bore * 1000:.2f} mm: declare the body's real bore")
            if all(mechkit.gap(sh, (rot, origin), outer, (rot, origin)) >= 0.0 for sh in solid):
                raise ValueError(f"rope {self.name}: slider {s.name} has no collider within 0.5 mm of its declared "
                                 f"bore {s.bore * 1000:.2f} mm: the body's bore is larger, or it does not surround "
                                 "the rope")
            self._clear_of_rope(f"slider {s.name}", s.body, rot, origin)
            for f in self.fixtures:
                rf, of = self.fixture_frame(f.name)
                for sa in s.body.shapes:
                    for sb in f.body.shapes:
                        if sa.collide and sb.collide and mechkit.gap(sa, (rot, origin), sb, (rf, of)) < -1e-6:
                            raise ValueError(f"rope {self.name}: slider {s.name} overlaps fixture {f.name} as laid")
        for a in range(len(sl)):
            for b in range(a + 1, len(sl)):
                ra, oa = self.slider_frame(sl[a].name)
                rb, ob = self.slider_frame(sl[b].name)
                for sa in sl[a].body.shapes:
                    for sb in sl[b].body.shapes:
                        if sa.collide and sb.collide and mechkit.gap(sa, (ra, oa), sb, (rb, ob)) < -1e-6:
                            raise ValueError(f"rope {self.name}: sliders {sl[a].name} and {sl[b].name} overlap")

    def _check_end_bodies(self) -> None:
        """End bodies must not start inside a segment they are not welded to, nor inside each other."""
        lay, r = self.layout, self.radius
        seg = mechkit.cyl((0.0, 0.0, 0.0), r, lay.seg_len, axis="x")
        for end in ENDS:
            b = self.body(end)
            if b is None:
                continue
            rot, origin = self.end_frame(end)
            welded = 0 if end == "start" else lay.n - 1
            for s in b.shapes:
                if not s.collide:
                    continue
                for j in range(lay.n):
                    if j == welded:
                        continue
                    g = mechkit.gap(s, (rot, origin), seg, (lay.rots[j], lay.centres[j]))
                    if g < -1e-6:
                        raise ValueError(f"rope {self.name}: the {end} body overlaps segment {j} by {-g * 1000:.2f} mm "
                                         "as laid")
        if self.start_body is not None and self.end_body is not None:
            ra, oa = self.end_frame("start")
            rb, ob = self.end_frame("end")
            for sa in self.start_body.shapes:
                for sb in self.end_body.shapes:
                    if sa.collide and sb.collide and mechkit.gap(sa, (ra, oa), sb, (rb, ob)) < -1e-6:
                        raise ValueError(f"rope {self.name}: the two end bodies overlap as laid")

    def report(self) -> list[str]:
        """Lines for check.py logs: segments, lengths, stiffness, the sharpest laid bend and the self clearance."""
        lay = self.layout
        bends = [jf.bend for jf in joint_frames(lay)]
        gap, pair = _self_clearance(lay, self.radius)
        lines = [f"{self.name}: {lay.n} segments of {lay.seg_len * 1000:.1f} mm, length {lay.length:.4f} m, radius "
                 f"{self.radius * 1000:.1f} mm, mass {self.rope_mass:.4g} kg, bend {self.bend_stiffness:.4g} N m/rad "
                 f"per joint, max_bend {math.degrees(self.max_bend):.0f} deg",
                 f"{self.name}: sharpest laid bend {math.degrees(max(bends)):.1f} deg, path overshoot "
                 f"{lay.overshoot * 1000:.2f} mm, lowest collider z {self.lowest():.4f} m"]
        if pair is not None:
            lines.append(f"{self.name}: least self clearance {gap * 1000:.2f} mm (segments {pair[0]} and {pair[1]})")
        if self.radius < TESTED_RADIUS:
            lines.append(f"{self.name}: radius {self.radius * 1000:.1f} mm is under the tested 3 mm: run it in the "
                         "simulator before relying on it")
        for f in self.fixtures:
            lines.append(f"{self.name}: fixture {f.name} welded to segment {self.fixture_segment(f.name)} at "
                         f"{f.at:.4f} m, {f.body.mass:.4g} kg, neighbours {'filtered' if f.filter_neighbours else 'collide'}"
                         ", clear of the rest as laid")
        sharpest = max(bends) if bends else 0.0
        for s in self.sliders:
            cap = self.captive(s.name)
            held = [e for e in ENDS if cap[e]]
            rot, origin = self.slider_frame(s.name)
            low = float((s.body.points() @ rot.T + origin)[:, 2].min())
            lines.append(f"{self.name}: slider {s.name} at {s.at:.4f} m, bore {s.bore * 1000:.2f} mm, clearance "
                         f"{self.slider_clearance(s.name) * 1000:.2f} mm per side, length {s.length() * 1000:.1f} mm, "
                         f"start clear of the rope, lowest z {low:.4f} m")
            lines.append(f"{self.name}: slider {s.name} rides over joint bends up to "
                         f"{math.degrees(self.pass_bend(s.name)):.1f} deg (sharpest laid bend {math.degrees(sharpest):.1f}"
                         f" deg); kept on at {', '.join(held) if held else 'neither end'}"
                         + ("" if len(held) == 2 else ": it can slide off a free end"))
        if self.plastic is not None:
            p = self.plastic
            lines.append(f"{self.name}: plastic {p.label or 'wire'}: stiffness {p.stiffness:.4g} N m/rad, yield "
                         f"{math.degrees(p.yield_angle):.2f} deg, yield moment {p.yield_moment:.4g} N m, damping "
                         f"{p.damping:.4g} N m s/rad; longest elastic overhang {max_elastic_overhang(self) * 100:.1f} cm")
            if p.segment is not None and abs(p.segment - lay.seg_len) > 0.1 * lay.seg_len:
                lines.append(f"{self.name}: plastic numbers were made for {p.segment * 1000:.1f} mm joints but the rope's "
                             f"are {lay.seg_len * 1000:.1f} mm: build them with the rope's segment length")
        return lines


def max_elastic_overhang(rope: Rope) -> float:
    """Longest free length (m) of the rope a plastic joint can hold out level against gravity and stay elastic: the
    rope's weight per metre w and the heavier free end body's weight W give w L^2 / 2 + W L = the yield moment (an
    anchored start's body is held by the world, so it loads nothing). A longer level overhang takes a set and droops
    (real yielding, not creep). Raises for a rope without ``plastic``."""
    if not isinstance(rope, Rope) or rope.plastic is None:
        raise ValueError("max_elastic_overhang: needs a Rope with plastic")
    w = rope.rope_mass / rope.total_length * mechkit.G
    free = (rope.end_body,) if rope.anchor_start else (rope.start_body, rope.end_body)
    W = max([0.0] + [b.mass for b in free if b is not None]) * mechkit.G
    M = rope.plastic.yield_moment
    return float((-W + math.sqrt(W * W + 2 * w * M)) / w)


