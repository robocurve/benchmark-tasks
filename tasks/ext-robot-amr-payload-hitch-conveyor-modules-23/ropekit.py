@dataclass(frozen=True)
class RopeState(ObjectState):
    """An ObjectState for a rope (bounding box of every collider, mean velocities, identity rotation) plus its shape.

    ``points`` (n, 3) segment centres from start to end, ``seg_quats`` (n, 4) their (x, y, z, w) rotations (x along
    the rope), ``end_poses`` maps "start" and "end" to (origin, quat xyzw) of the end frame: the welded end body's pose
    when there is one, else the bare tip's. ``bodies`` maps each end to whether it carries a body."""

    points: np.ndarray = field(default_factory=lambda: np.zeros((0, 3)))
    seg_quats: np.ndarray = field(default_factory=lambda: np.zeros((0, 4)))
    end_poses: dict = field(default_factory=dict)
    bodies: dict = field(default_factory=dict)
    seg_len: float = 0.0
    radius: float = 0.0
    fixtures: dict = field(default_factory=dict)
    sliders: dict = field(default_factory=dict)
    slider_bores: dict = field(default_factory=dict)
    set_bends: np.ndarray | None = None
    laid_rels: np.ndarray | None = None

    # ``fixtures`` and ``sliders`` map a name to (origin, quat xyzw) of its frame (origin on the rope axis at its
    # point, +x along the rope); ``set_bends`` is the plastic set, (n - 1, 2) rad per joint (None without plastic).

    @property
    def length(self) -> float:
        """Nominal length (m): segments x segment length."""
        return len(self.points) * self.seg_len

    def _axis(self, i: int) -> np.ndarray:
        return mechkit._quat_xyzw_matrix(self.seg_quats[i])[:, 0]

    def tip(self, end: str) -> np.ndarray:
        """The bare tip of the end segment (not of any end body)."""
        if end == "start":
            return self.points[0] - self._axis(0) * self.seg_len / 2
        if end == "end":
            return self.points[-1] + self._axis(-1) * self.seg_len / 2
        raise ValueError(f"rope end must be 'start' or 'end', got {end!r}")

    def polyline(self) -> np.ndarray:
        """Start tip, every joint, end tip: (n + 1, 3), from the segment poses."""
        ax = np.array([self._axis(i) for i in range(len(self.points))])
        return np.vstack([self.points - ax * self.seg_len / 2, self.points[-1:] + ax[-1:] * self.seg_len / 2])

    def arclength(self) -> np.ndarray:
        """Distance (m) along the rope of each segment centre from the start tip."""
        return (np.arange(len(self.points)) + 0.5) * self.seg_len

    def measured_length(self) -> float:
        """Length (m) through the segment centres plus the two half end segments: equals ``length`` for a straight
        rope and is a little shorter where it bends. Far over ``length`` means the chain has pulled apart."""
        return polyline_length(self.points) + self.seg_len

    def point_at(self, s: float) -> np.ndarray:
        """The point ``s`` metres along the rope from its start tip (clipped to the rope)."""
        k = self.polyline()
        s = float(np.clip(_num("arclength", s), 0.0, self.length))
        i = min(int(s // self.seg_len), len(k) - 2)
        u = (s - i * self.seg_len) / self.seg_len
        return k[i] + u * (k[i + 1] - k[i])

    def nearest_arclength(self, point) -> float:
        """Arclength (m) of the point on the rope nearest ``point``."""
        k = self.polyline()
        p = np.asarray(point, dtype=float)
        best, s_best = math.inf, 0.0
        for i in range(len(k) - 1):
            d = k[i + 1] - k[i]
            u = float(np.clip((p - k[i]) @ d / (d @ d), 0.0, 1.0))
            dist = float(np.linalg.norm(k[i] + u * d - p))
            if dist < best:
                best, s_best = dist, (i + u) * self.seg_len
        return s_best

    def end_point(self, end: str, local=(0.0, 0.0, 0.0)) -> np.ndarray:
        """A point given in an end frame (origin at the tip, +x away from the rope; an end body's own frame) in the
        world."""
        if end not in ENDS:
            raise ValueError(f"rope end must be 'start' or 'end', got {end!r}")
        if end not in self.end_poses:
            raise ValueError(f"rope state has no {end} pose")
        origin, quat = self.end_poses[end]
        return mechkit._quat_xyzw_matrix(quat) @ np.asarray(local, dtype=float) + np.asarray(origin, dtype=float)

    def end_axis(self, end: str) -> np.ndarray:
        """Unit vector pointing out of the rope at that end (the end frame's +x)."""
        return self.end_point(end, (1.0, 0.0, 0.0)) - self.end_point(end)

    def end_distance(self, end: str, target, local=(0.0, 0.0, 0.0)) -> float:
        """Distance (m) from a point in the end frame to ``target`` (world)."""
        return float(np.linalg.norm(self.end_point(end, local) - np.asarray(target, dtype=float)))

    def _arc(self, a) -> float:
        if isinstance(a, (int, float)) and not isinstance(a, bool):
            return float(np.clip(a, 0.0, self.length))
        p = np.asarray(a, dtype=float)
        if p.shape != (3,):
            raise ValueError(f"sag: give an arclength (m) or a world point (x, y, z), got {a!r}")
        return self.nearest_arclength(p)

    def sag(self, a=0.0, b=None) -> float:
        """Largest drop (m) of the rope below the straight line between two of its points, measured vertically at
        the same horizontal position. ``a`` and ``b`` are arclengths (m from the start tip) or world points (the
        nearest rope point is used); ``b`` defaults to the end tip. Negative when the rope arches above the line.
        Raises when the two points are under 1 mm apart horizontally."""
        sa, sb = self._arc(a), self._arc(self.length if b is None else b)
        if sb < sa:
            sa, sb = sb, sa
        A, B = self.point_at(sa), self.point_at(sb)
        h = B[:2] - A[:2]
        if float(h @ h) < 1e-6:
            raise ValueError("sag: the two points are under 1 mm apart horizontally")
        k = self.polyline()
        s_k = np.arange(len(k)) * self.seg_len
        inner = [self.point_at(sa)] + [k[i] for i in range(len(k)) if sa < s_k[i] < sb] + [self.point_at(sb)]
        best = -math.inf
        for p in inner:
            t = float(np.clip((p[:2] - A[:2]) @ h / (h @ h), 0.0, 1.0))
            best = max(best, A[2] + t * (B[2] - A[2]) - float(p[2]))
        return float(best)

    def crossings(self, centre, normal, radius: float) -> list[tuple[float, int]]:
        """Where the rope's centre line crosses the disc of ``radius`` round ``centre`` facing ``normal``: a list of
        (arclength, +1 along the normal or -1 against it)."""
        c = np.asarray(centre, dtype=float)
        n = np.asarray(normal, dtype=float)
        if n.shape != (3,) or np.linalg.norm(n) < 1e-12:
            raise ValueError("crossings: normal must be a nonzero (x, y, z)")
        n = n / np.linalg.norm(n)
        R = _num("crossings radius", radius, 0.0, low_open=True)
        k = self.polyline()
        d = (k - c) @ n
        out = []
        for i in range(len(k) - 1):
            if (d[i] < 0) != (d[i + 1] < 0) and d[i] != d[i + 1]:
                u = d[i] / (d[i] - d[i + 1])
                p = k[i] + u * (k[i + 1] - k[i])
                if np.linalg.norm(p - c) <= R:
                    out.append(((i + u) * self.seg_len, 1 if d[i + 1] > d[i] else -1))
        return out

    def passes_through(self, centre, normal, radius: float) -> bool:
        """True when the rope is threaded through the ring (an odd net count of crossings of its disc): through and
        back out the same side counts as not threaded. ``radius`` is the ring's clear inner radius."""
        return sum(sign for _, sign in self.crossings(centre, normal, radius)) != 0

    def wrap_angle(self, xy, z_low: float = -math.inf, z_high: float = math.inf) -> float:
        """Signed angle (rad, counter-clockwise from above positive) the rope's centre line turns round the vertical
        axis through ``xy``, counting only pieces with both ends between ``z_low`` and ``z_high``."""
        k = self.polyline()
        c = np.asarray(_floats(xy), dtype=float)
        if c.shape != (2,):
            raise ValueError("wrap_angle: xy must be (x, y)")
        total = 0.0
        for i in range(len(k) - 1):
            if not (z_low <= k[i][2] <= z_high and z_low <= k[i + 1][2] <= z_high):
                continue
            a, b = k[i][:2] - c, k[i + 1][:2] - c
            if np.linalg.norm(a) < 1e-9 or np.linalg.norm(b) < 1e-9:
                continue
            total += math.atan2(a[0] * b[1] - a[1] * b[0], float(a @ b))
        return float(total)

    def round_post(self, xy, min_angle: float = math.pi, z_low: float = -math.inf, z_high: float = math.inf) -> bool:
        """True when the rope wraps at least ``min_angle`` (rad, either way) round the post at ``xy``."""
        return abs(self.wrap_angle(xy, z_low, z_high)) >= _num("min_angle", min_angle, 0.0)

    def lowest(self) -> float:
        """Lowest segment surface z (m), ignoring end bodies."""
        return float(self.points[:, 2].min() - self.radius)

    # -- bodies along the rope -------------------------------------------------------------------------------------------

    def _pose(self, table: dict, kind: str, name: str):
        if name not in table:
            raise ValueError(f"rope state has no {kind} {name!r} (has {sorted(table)})")
        origin, quat = table[name]
        return np.asarray(origin, dtype=float), np.asarray(quat, dtype=float)

    def fixture_pose(self, name: str) -> tuple[np.ndarray, np.ndarray]:
        """(origin, quat xyzw) of a fixture's frame."""
        return self._pose(self.fixtures, "fixture", name)

    def fixture_point(self, name: str, local=(0.0, 0.0, 0.0)) -> np.ndarray:
        """A point given in a fixture's frame, in the world."""
        origin, quat = self.fixture_pose(name)
        return mechkit._quat_xyzw_matrix(quat) @ np.asarray(local, dtype=float) + origin

    def slider_pose(self, name: str) -> tuple[np.ndarray, np.ndarray]:
        """(origin, quat xyzw) of a slider's frame (its Mech pose with the start frame turn applied)."""
        return self._pose(self.sliders, "slider", name)

    def slider_point(self, name: str, local=(0.0, 0.0, 0.0)) -> np.ndarray:
        """A point given in a slider's frame, in the world."""
        origin, quat = self.slider_pose(name)
        return mechkit._quat_xyzw_matrix(quat) @ np.asarray(local, dtype=float) + origin

    def slider_arclength(self, name: str) -> float:
        """Arclength (m from the start tip) of the rope point nearest the slider's centre: where along the rope it is."""
        return self.nearest_arclength(self.slider_pose(name)[0])

    def slider_offset(self, name: str) -> float:
        """Distance (m) from the slider's centre to the nearest point of the rope's centre line."""
        p = self.slider_pose(name)[0]
        return float(np.linalg.norm(self.point_at(self.nearest_arclength(p)) - p))

    def slider_on_rope(self, name: str, tol: float = 0.003) -> bool:
        """True when the slider's centre is within its bore clearance (plus ``tol``, m, for the chord polyline and a
        bend inside the bore) of the rope's centre line and not past either tip: it is still threaded. Off an end,
        its nearest rope point is a tip and the offset grows."""
        if name not in self.slider_bores:
            raise ValueError(f"rope state has no slider {name!r}")
        p = self.slider_pose(name)[0]
        s = self.nearest_arclength(p)
        along = (p - self.point_at(s))
        if s <= 1e-9 or s >= self.length - 1e-9:  # nearest point is a tip: is it still inside the bore's length?
            end = "start" if s <= 1e-9 else "end"
            if float(along @ self.end_axis(end)) > tol:
                return False
        return self.slider_offset(name) <= self.slider_bores[name] - self.radius + _num("tol", tol, 0.0)

    # -- bends and the plastic set ---------------------------------------------------------------------------------------

    def tangent_at(self, s: float) -> np.ndarray:
        """Unit direction of the rope (start to end) at arclength ``s``: the axis of the segment there."""
        s = float(np.clip(_num("arclength", s), 0.0, self.length))
        i = _seg_index(s, self.seg_len, len(self.points))
        return self._axis(i)

    def bend_angles(self) -> np.ndarray:
        """(n - 1,) angle (rad) between each pair of neighbouring segments, as they are now (not from the laid shape)."""
        ax = np.array([self._axis(i) for i in range(len(self.points))])
        return np.arccos(np.clip(np.einsum("ij,ij->i", ax[:-1], ax[1:]), -1.0, 1.0))

    def turn_angle(self, a: float, b: float) -> float:
        """Angle (rad, 0 to pi) between the rope's direction at arclengths ``a`` and ``b``: about pi / 2 across a
        right-angle bend, pi across a U."""
        return float(math.acos(float(np.clip(self.tangent_at(a) @ self.tangent_at(b), -1.0, 1.0))))

    def set_polyline(self) -> np.ndarray:
        """Knots (n + 1, 3) of the shape the rope's set would give it unloaded, built from segment 0 as it is now and
        every joint at its set (each joint's laid turn, then its set bend). Raises without plastic."""
        if self.set_bends is None or self.laid_rels is None:
            raise ValueError("rope state has no plastic set")
        return _chain_knots(mechkit._quat_xyzw_matrix(self.seg_quats[0]), self.points[0], self.laid_rels,
                            self.set_bends, self.seg_len)

    def set_turn(self, a: float, b: float) -> float:
        """Angle (rad) between the set shape's directions at arclengths ``a`` and ``b``: the bend the wire keeps."""
        k = self.set_polyline()
        n = len(k) - 1

        def tan(s):
            s = float(np.clip(_num("arclength", s), 0.0, self.length))
            i = _seg_index(s, self.seg_len, n)
            d = k[i + 1] - k[i]
            return d / np.linalg.norm(d)

        return float(math.acos(float(np.clip(tan(a) @ tan(b), -1.0, 1.0))))

    def frame_at(self, s: float) -> tuple[np.ndarray, np.ndarray]:
        """(rotation, point) of the rope at arclength ``s`` now: the segment's rotation and the point on its axis."""
        s = float(np.clip(_num("arclength", s), 0.0, self.length))
        i = _seg_index(s, self.seg_len, len(self.points))
        rot = mechkit._quat_xyzw_matrix(self.seg_quats[i])
        return rot, self.points[i] + rot[:, 0] * (s - (i + 0.5) * self.seg_len)


def slider_arclength(rope_state: RopeState, slider_state) -> float:
    """Arclength (m) along ``rope_state`` of the slider whose own state (a MechState or ObjectState from score()'s
    objects) is ``slider_state``: the rope point nearest its origin (its centre for a plain ObjectState)."""
    p = getattr(slider_state, "origin", None)
    if p is None:
        p = slider_state.pos
    return rope_state.nearest_arclength(np.asarray(p, dtype=float))


def _end_frames(points: np.ndarray, quats: np.ndarray, seg_len: float) -> dict:
    """Bare tip frames from segment poses: (origin, quat xyzw) for each end."""
    r0 = mechkit._quat_xyzw_matrix(quats[0])
    rn = mechkit._quat_xyzw_matrix(quats[-1])
    start = (points[0] - r0[:, 0] * seg_len / 2, np.array(_xyzw(_matrix_quat(r0 @ _quat_matrix(_FLIP)))))
    end = (points[-1] + rn[:, 0] * seg_len / 2, np.asarray(quats[-1], dtype=float))
    return {"start": start, "end": end}


def _state(spec: Rope, points, quats, bodies: dict, lin=None, ang=None, fixtures=None, sliders=None,
           set_bends=None) -> RopeState:
    """A RopeState from segment poses (world, env origin removed), end-body poses {end: (pos, quat xyzw)}, fixture
    poses {name: (pos, quat xyzw)} (every fixture), slider frame poses {name: (pos, quat xyzw)} and the plastic set
    ((n - 1, 2) rad; zeros when the rope is plastic and none is given)."""
    points = np.asarray(points, dtype=float).reshape(-1, 3)
    quats = np.asarray(quats, dtype=float).reshape(-1, 4)
    if len(points) != spec.segments or len(quats) != spec.segments:
        raise ValueError(f"rope {spec.name}: expected {spec.segments} segment poses, got {len(points)}")
    poses = _end_frames(points, quats, spec.seg_len)
    pts = [points - spec.radius, points + spec.radius]
    for end in ENDS:
        b = spec.body(end)
        if b is None:
            if end in bodies:
                raise ValueError(f"rope {spec.name}: a {end} body pose was given but the rope has no {end} body")
            continue
        if end not in bodies:
            raise ValueError(f"rope {spec.name}: no pose for its {end} body")
        pos, quat = bodies[end]
        poses[end] = (np.asarray(pos, dtype=float), np.asarray(quat, dtype=float))
        pts.append(b.points() @ mechkit._quat_xyzw_matrix(quat).T + np.asarray(pos, dtype=float))
    fixtures = dict(fixtures or {})
    fx = {}
    for f in spec.fixtures:
        if f.name not in fixtures:
            raise ValueError(f"rope {spec.name}: no pose for its fixture {f.name}")
        pos, quat = fixtures.pop(f.name)
        fx[f.name] = (np.asarray(pos, dtype=float), np.asarray(quat, dtype=float))
        pts.append(f.body.points() @ mechkit._quat_xyzw_matrix(quat).T + fx[f.name][0])
    if fixtures:
        raise ValueError(f"rope {spec.name}: poses given for unknown fixtures {sorted(fixtures)}")
    known = {s.name: s for s in spec.sliders}
    sl = {}
    for name, (pos, quat) in dict(sliders or {}).items():
        if name not in known:
            raise ValueError(f"rope {spec.name}: a pose was given for unknown slider {name!r}")
        sl[name] = (np.asarray(pos, dtype=float), np.asarray(quat, dtype=float))
    sb = None
    if spec.plastic is not None:
        sb = np.zeros((spec.segments - 1, 2)) if set_bends is None else np.asarray(set_bends, dtype=float)
        if sb.shape != (spec.segments - 1, 2):
            raise ValueError(f"rope {spec.name}: set_bends must be ({spec.segments - 1}, 2), got {sb.shape}")
    elif set_bends is not None:
        raise ValueError(f"rope {spec.name}: set_bends given but the rope is not plastic")
    allp = np.vstack(pts)
    lo, hi = allp.min(0), allp.max(0)
    return RopeState(pos=(lo + hi) / 2, quat_xyzw=np.array([0.0, 0.0, 0.0, 1.0]),
                     lin_vel=np.zeros(3) if lin is None else np.asarray(lin, dtype=float),
                     ang_vel=np.zeros(3) if ang is None else np.asarray(ang, dtype=float), low=lo, high=hi,
                     points=points, seg_quats=quats, end_poses=poses,
                     bodies={e: spec.body(e) is not None for e in ENDS}, seg_len=spec.seg_len, radius=spec.radius,
                     fixtures=fx, sliders=sl, slider_bores={s.name: float(s.bore) for s in spec.sliders},
                     set_bends=sb, laid_rels=spec.laid_rels() if sb is not None else None)


def mock_state(rope: Rope, points=None, sliders=None, set_bends=None) -> RopeState:
    """A RopeState for offline dry runs: the laid pose, or segment centres ``points`` (n, 3) with each segment turned
    along the line through its neighbours. End bodies and fixtures sit welded where they belong. Each slider sits on
    the rope at its start arclength, or at ``sliders[name]`` (m) when given; ``set_bends`` ((n - 1, 2) rad) is the
    plastic set (zeros by default for a plastic rope). Nothing here reads a simulator."""
    if not isinstance(rope, Rope):
        raise ValueError(f"mock_state: expected a Rope, got {type(rope).__name__}")
    lay = rope.layout
    if points is None:
        pts, rots = lay.centres.copy(), lay.rots
    else:
        pts = np.asarray(points, dtype=float).reshape(-1, 3)
        if len(pts) != lay.n:
            raise ValueError(f"mock_state: {rope.name} has {lay.n} segments, got {len(pts)} points")
        ext = np.vstack([2 * pts[0] - pts[1], pts, 2 * pts[-1] - pts[-2]])
        rots = np.array([_frame(ext[i + 2] - ext[i]) for i in range(lay.n)])
    quats = np.array([_xyzw(_matrix_quat(r)) for r in rots])
    bodies = {}
    frames = _end_frames(pts, quats, lay.seg_len)
    for end in ENDS:
        if rope.body(end) is not None:
            bodies[end] = frames[end]
    L = lay.seg_len

    def frame(s: float):
        i = _seg_index(s, L, lay.n)
        return pts[i] + rots[i][:, 0] * (s - (i + 0.5) * L), np.array(_xyzw(_matrix_quat(rots[i])))

    fixtures = {f.name: frame(f.at) for f in rope.fixtures}
    where = {s.name: s.at for s in rope.sliders}
    for name, s in dict(sliders or {}).items():
        if name not in where:
            raise ValueError(f"mock_state: {rope.name} has no slider {name!r}")
        where[name] = float(np.clip(_num(f"slider {name} arclength", s), 0.0, lay.length))
    return _state(rope, pts, quats, bodies, fixtures=fixtures, sliders={n: frame(s) for n, s in where.items()},
                  set_bends=set_bends)


# -- building it in Isaac Sim ------------------------------------------------------------------------------------------

_ROPES: dict[str, Rope] = {}
_SET: dict[str, np.ndarray] = {}  # plastic rope name -> (envs, n - 1, 2) set bends (rad) last written as targets


def set_shape(name: str) -> np.ndarray | None:
    """The plastic set of rope ``name`` in env 0, (n - 1, 2) rad per joint, as the on_step hook last wrote it (a copy);
    None before the first step or for a rope that is not plastic. RopeState.set_bends carries the same to score()."""
    s = _SET.get(name)
    return None if s is None else np.array(s[0], dtype=float)


def _author(prim_path: str, cfg: Any, translation=None, orientation=None, **_: Any):
    """Write the rope to USD: segments seg_0 .. seg_{n-1} (seg_0 is the articulation root), D6 bend joints, optional
    end bodies welded on, an optional world anchor. Every number given to USD is a plain float."""
    import isaaclab.sim as sim_utils
    from isaaclab.sim.utils import bind_physics_material, bind_visual_material
    from isaaclab.sim.utils.stage import get_current_stage
    from pxr import Gf, PhysxSchema, Sdf, UsdGeom, UsdPhysics, Vt

    from yam_arena.station import linear_rgb

    spec = _ROPES[cfg.rope_name]
    lay = spec.layout
    L, r, n = float(lay.seg_len), float(spec.radius), lay.n
    stage = get_current_stage()
    root = UsdGeom.Xform.Define(stage, prim_path)
    root.AddTranslateOp(precision=UsdGeom.XformOp.PrecisionDouble).Set(
        Gf.Vec3d(*_floats((0.0, 0.0, 0.0) if translation is None else translation)))
    x, y, z, w = _floats(orientation) if orientation is not None else (0.0, 0.0, 0.0, 1.0)
    root.AddOrientOp(precision=UsdGeom.XformOp.PrecisionDouble).Set(Gf.Quatd(w, x, y, z))

    looks: dict = {}

    def look(color) -> str:
        key = _floats(color)
        if key not in looks:
            path = f"{prim_path}/Looks/color{len(looks)}"
            mat = sim_utils.PreviewSurfaceCfg(diffuse_color=linear_rgb(key), roughness=0.5)
            mat.func(path, mat)
            looks[key] = path
        return looks[key]

    def material(tag: str, mu: float) -> str:
        path = f"{prim_path}/Looks/{tag}"
        mat = sim_utils.RigidBodyMaterialCfg(static_friction=float(mu), dynamic_friction=float(mu))
        mat.func(path, mat)
        return path

    phys = material("rope_physics", spec.friction)
    poses = spec.body_poses()

    def body(name: str, mass: float) -> str:
        path = f"{prim_path}/{name}"
        pos, quat = poses[name]
        xf = UsdGeom.Xform.Define(stage, path)
        xf.AddTranslateOp(precision=UsdGeom.XformOp.PrecisionDouble).Set(Gf.Vec3d(*pos))
        xf.AddOrientOp(precision=UsdGeom.XformOp.PrecisionDouble).Set(Gf.Quatd(*quat))
        prim = xf.GetPrim()
        UsdPhysics.RigidBodyAPI.Apply(prim)
        UsdPhysics.MassAPI.Apply(prim).CreateMassAttr(float(mass))
        rb = PhysxSchema.PhysxRigidBodyAPI.Apply(prim)
        rb.CreateMaxDepenetrationVelocityAttr(MAX_DEPENETRATION)
        rb.CreateSolverPositionIterationCountAttr(POSITION_ITERATIONS)
        rb.CreateLinearDampingAttr(LINEAR_DAMPING)
        rb.CreateAngularDampingAttr(ANGULAR_DAMPING)
        return path

    def collide(prim, mat: str, contact: float) -> None:
        UsdPhysics.CollisionAPI.Apply(prim)
        c = PhysxSchema.PhysxCollisionAPI.Apply(prim)
        c.CreateContactOffsetAttr(float(contact))
        c.CreateRestOffsetAttr(0.0)
        bind_physics_material(str(prim.GetPath()), mat)

    def mesh_prim(path: str, piece):
        pts, counts, idx, normals = mechkit._usd_mesh_arrays(piece)
        m = UsdGeom.Mesh.Define(stage, path)
        m.CreatePointsAttr(Vt.Vec3fArray([Gf.Vec3f(*_floats(p)) for p in pts]))
        m.CreateFaceVertexCountsAttr(Vt.IntArray([int(c) for c in counts]))
        m.CreateFaceVertexIndicesAttr(Vt.IntArray([int(i) for i in idx]))
        m.CreateSubdivisionSchemeAttr(UsdGeom.Tokens.none)
        lo, hi = np.min(pts, axis=0), np.max(pts, axis=0)
        m.CreateExtentAttr(Vt.Vec3fArray([Gf.Vec3f(*_floats(lo)), Gf.Vec3f(*_floats(hi))]))
        if normals is not None:
            m.CreateNormalsAttr(Vt.Vec3fArray([Gf.Vec3f(*_floats(nv)) for nv in normals]))
            m.SetNormalsInterpolation(UsdGeom.Tokens.faceVarying)
        return m

    def hull_prims(path: str, shape: Shape, mat: str) -> None:
        for k, piece in enumerate(shape.hulls):
            h = mesh_prim(f"{path}/hull{k:02d}", piece)
            h.CreatePurposeAttr(UsdGeom.Tokens.guide)
            prim = h.GetPrim()
            UsdPhysics.MeshCollisionAPI.Apply(prim).CreateApproximationAttr(UsdPhysics.Tokens.convexHull)
            cv = PhysxSchema.PhysxConvexHullCollisionAPI.Apply(prim)
            cv.CreateHullVertexLimitAttr(mechkit.HULL_VERTEX_LIMIT)
            cv.CreateMinThicknessAttr(1e-5)
            collide(prim, mat, mechkit.contact_offset(shape))

    def add_shape(path: str, shape: Shape, mat: str) -> None:
        """A mechkit Shape on an end body, authored as mechkit authors it."""
        if shape.kind == "mesh":
            xf = UsdGeom.Xform.Define(stage, path)
            xf.AddTranslateOp(precision=UsdGeom.XformOp.PrecisionDouble).Set(Gf.Vec3d(*_floats(shape.at)))
            xf.AddOrientOp(precision=UsdGeom.XformOp.PrecisionDouble).Set(Gf.Quatd(*_floats(shape.tilt)))
            if shape.visible:
                mesh_prim(f"{path}/visual", shape.visual)
                bind_visual_material(f"{path}/visual", look(shape.color))
            if shape.collide:
                hull_prims(path, shape, mat)
            return
        if shape.kind == "cyl":
            geom = UsdGeom.Cylinder.Define(stage, path)
            geom.CreateRadiusAttr(float(shape.size[0]))
            geom.CreateHeightAttr(float(shape.size[2]))
            geom.CreateAxisAttr(shape.axis.upper())
            scale = Gf.Vec3f(1.0, 1.0, 1.0)
        elif shape.kind == "box":
            geom = UsdGeom.Cube.Define(stage, path)
            geom.CreateSizeAttr(1.0)
            scale = Gf.Vec3f(*_floats(shape.size))
        else:
            raise ValueError(f"unknown shape kind {shape.kind!r}")
        geom.AddTranslateOp(precision=UsdGeom.XformOp.PrecisionDouble).Set(Gf.Vec3d(*_floats(shape.at)))
        geom.AddOrientOp(precision=UsdGeom.XformOp.PrecisionDouble).Set(Gf.Quatd(*_floats(shape.tilt)))
        geom.AddScaleOp().Set(scale)
        if not shape.visible:
            geom.CreatePurposeAttr(UsdGeom.Tokens.guide)
        bind_visual_material(path, look(shape.color))
        if shape.collide:
            collide(geom.GetPrim(), mat, mechkit.contact_offset(shape))

    sides = int(spec.collision_sides)
    collider = None
    if sides:
        collider = segment_collider(L, r, sides)
    seg_paths = []
    for i in range(n):
        path = body(f"seg_{i}", spec.rope_mass / n)
        cap = UsdGeom.Capsule.Define(stage, f"{path}/geom")
        cap.CreateAxisAttr("X")
        cap.CreateRadiusAttr(r)
        cap.CreateHeightAttr(float(max(L - 2 * r, 1e-4) + 2 * r * 0.9))  # slight overlap: no gaps when bent
        bind_visual_material(str(cap.GetPath()), look(spec.color))
        if collider is not None:
            add_shape(f"{path}/collider", collider, phys)  # hidden hull, placed at its own at / tilt
        else:
            collide(cap.GetPrim(), phys, CONTACT)
        seg_paths.append(path)

    for jf in joint_frames(lay):
        parent, child = seg_paths[jf.index - 1], seg_paths[jf.index]
        j = UsdPhysics.Joint.Define(stage, f"{child}/bend_{jf.index}")
        j.CreateBody0Rel().SetTargets([Sdf.Path(parent)])
        j.CreateBody1Rel().SetTargets([Sdf.Path(child)])
        j.CreateLocalPos0Attr(Gf.Vec3f(*jf.pos0))
        j.CreateLocalRot0Attr(Gf.Quatf(*jf.rot0))
        j.CreateLocalPos1Attr(Gf.Vec3f(*jf.pos1))
        j.CreateLocalRot1Attr(Gf.Quatf(*jf.rot1))
        prim = j.GetPrim()
        for dof in ("transX", "transY", "transZ", "rotX"):  # no stretch, no twist: low above high locks the axis
            lim = UsdPhysics.LimitAPI.Apply(prim, dof)
            lim.CreateLowAttr(1.0)
            lim.CreateHighAttr(-1.0)
        for dof in ("rotY", "rotZ"):
            lim = UsdPhysics.LimitAPI.Apply(prim, dof)
            lim.CreateLowAttr(float(-math.degrees(spec.max_bend)))
            lim.CreateHighAttr(float(math.degrees(spec.max_bend)))
            drv = UsdPhysics.DriveAPI.Apply(prim, dof)
            drv.CreateTypeAttr("force")
            drv.CreateStiffnessAttr(float(spec.bend_stiffness * math.pi / 180))  # USD angular gains are per degree
            drv.CreateDampingAttr(float(spec.bend_damping * math.pi / 180))
            drv.CreateTargetPositionAttr(0.0)

    for end in ENDS:
        b = spec.body(end)
        if b is None:
            continue
        path = body(f"{end}_body", b.mass)
        mat = phys if b.friction is None else material(f"{end}_physics", b.friction)
        for i, shape in enumerate(b.shapes):
            add_shape(f"{path}/shape{i}", shape, mat)
        seg = seg_paths[0] if end == "start" else seg_paths[-1]
        weld = UsdPhysics.FixedJoint.Define(stage, f"{path}/weld")  # the body is the child: the tree stays rooted
        weld.CreateBody0Rel().SetTargets([Sdf.Path(seg)])
        weld.CreateBody1Rel().SetTargets([Sdf.Path(path)])
        weld.CreateLocalPos0Attr(Gf.Vec3f((-L / 2) if end == "start" else (L / 2), 0.0, 0.0))
        weld.CreateLocalRot0Attr(Gf.Quatf(*(_FLIP if end == "start" else IDENT)))
        weld.CreateLocalPos1Attr(Gf.Vec3f(0.0, 0.0, 0.0))
        weld.CreateLocalRot1Attr(Gf.Quatf(1.0, 0.0, 0.0, 0.0))

    for f in spec.fixtures:  # welded to its segment like an end body, offset along the segment's axis
        i = spec.fixture_segment(f.name)
        path = body(f"fix_{f.name}", f.body.mass)
        mat = phys if f.body.friction is None else material(f"fix_{f.name}_physics", f.body.friction)
        for k, shape in enumerate(f.body.shapes):
            add_shape(f"{path}/shape{k}", shape, mat)
        weld = UsdPhysics.FixedJoint.Define(stage, f"{path}/weld")
        weld.CreateBody0Rel().SetTargets([Sdf.Path(seg_paths[i])])
        weld.CreateBody1Rel().SetTargets([Sdf.Path(path)])
        weld.CreateLocalPos0Attr(Gf.Vec3f(float(f.at - (i + 0.5) * L), 0.0, 0.0))
        weld.CreateLocalRot0Attr(Gf.Quatf(*IDENT))
        weld.CreateLocalPos1Attr(Gf.Vec3f(0.0, 0.0, 0.0))
        weld.CreateLocalRot1Attr(Gf.Quatf(*IDENT))
        if f.filter_neighbours:
            near = [Sdf.Path(seg_paths[j]) for j in (i - 1, i + 1) if 0 <= j < n]
            if near:
                UsdPhysics.FilteredPairsAPI.Apply(stage.GetPrimAtPath(path)).CreateFilteredPairsRel().SetTargets(near)

    # Root API on seg_0 itself, so Isaac Lab's root pose is seg_0's pose (as the accepted cable kits do).
    root_link = stage.GetPrimAtPath(seg_paths[0])
    UsdPhysics.ArticulationRootAPI.Apply(root_link)
    art = PhysxSchema.PhysxArticulationAPI.Apply(root_link)
    art.CreateEnabledSelfCollisionsAttr(bool(spec.self_collision))
    art.CreateSolverPositionIterationCountAttr(POSITION_ITERATIONS)
    art.CreateSolverVelocityIterationCountAttr(VELOCITY_ITERATIONS)
    if spec.anchor_start:
        anchor = seg_paths[0] if spec.start_body is None else f"{prim_path}/start_body"
        fj = UsdPhysics.FixedJoint.Define(stage, f"{prim_path}/anchor")
        fj.CreateBody1Rel().SetTargets([Sdf.Path(anchor)])
        world = UsdGeom.Xformable(stage.GetPrimAtPath(anchor)).ComputeLocalToWorldTransform(0)
        t = world.ExtractTranslation()
        q = world.ExtractRotationQuat()
        fj.CreateLocalPos0Attr(Gf.Vec3f(float(t[0]), float(t[1]), float(t[2])))
        im = q.GetImaginary()
        fj.CreateLocalRot0Attr(Gf.Quatf(float(q.GetReal()), float(im[0]), float(im[1]), float(im[2])))
        fj.CreateLocalPos1Attr(Gf.Vec3f(0.0, 0.0, 0.0))
        fj.CreateLocalRot1Attr(Gf.Quatf(1.0, 0.0, 0.0, 0.0))
    return root.GetPrim()


def _arena_object(spec: Rope):
    """The rope as an Arena articulation; one implicit actuator group carries every bend spring."""
    from isaaclab.actuators import ImplicitActuatorCfg
    from isaaclab.assets import ArticulationCfg
    from isaaclab.sim.spawners.spawner_cfg import SpawnerCfg
    from isaaclab.sim.utils import clone
    from isaaclab.utils import configclass
    from isaaclab_arena.assets.object import Object
    from isaaclab_arena.assets.object_type import ObjectType
    from isaaclab_arena.utils.pose import Pose

    @configclass
    class RopeSpawnerCfg(SpawnerCfg):
        func: object = clone(_author)
        rope_name: str = ""

    class RopeObject(Object):
        def _generate_articulation_cfg(self):
            cfg = ArticulationCfg(prim_path=self.prim_path, spawn=self.spawner_cfg,
                                  actuators={"bend": ImplicitActuatorCfg(joint_names_expr=[".*"],
                                                                         stiffness=float(spec.bend_stiffness),
                                                                         damping=float(spec.bend_damping),
                                                                         armature=float(spec.armature))})
            return self._add_initial_pose_to_cfg(cfg)

    _ROPES[spec.name] = spec
    pos, quat = spec.root_pose()
    return RopeObject(name=spec.name, object_type=ObjectType.ARTICULATION,
                      spawner_cfg=RopeSpawnerCfg(rope_name=spec.name),
                      initial_pose=Pose(position_xyz=pos, rotation_xyzw=quat))


def _data(asset, *names: str):
    for n in names:
        v = getattr(asset.data, n, None)
        if v is not None:
            return mechkit._to_numpy(v)[0]
    raise AttributeError(f"ropekit: the articulation data has none of {names}")


def _rope_state(environment, spec: Rope) -> RopeState:
    base = environment.unwrapped
    asset = base.scene[spec.name]
    env0 = mechkit._to_numpy(base.scene.env_origins)[0]
    names = list(asset.body_names)
    pose = _data(asset, "body_link_pose_w")  # (bodies, 7): x, y, z, qx, qy, qz, qw
    lin = _data(asset, "body_link_lin_vel_w", "body_lin_vel_w")
    ang = _data(asset, "body_link_ang_vel_w", "body_ang_vel_w")
    idx = [names.index(f"seg_{i}") for i in range(spec.segments)]
    pts = pose[idx, :3] - env0
    quats = pose[idx, 3:7]
    bodies = {}
    for end in ENDS:
        if spec.body(end) is not None:
            k = names.index(f"{end}_body")
            bodies[end] = (pose[k, :3] - env0, pose[k, 3:7])
    fixtures = {}
    for f in spec.fixtures:
        k = names.index(f"fix_{f.name}")
        fixtures[f.name] = (pose[k, :3] - env0, pose[k, 3:7])
    sliders = {}
    for s in spec.sliders:  # its own rigid object: Mech pose, then the start frame's turn
        obj = base.scene[s.name]
        p = mechkit._to_numpy(obj.data.root_link_pose_w)[0]
        frame = mechkit._quat_xyzw_matrix(p[3:7]) @ spec.slider_frame(s.name)[0]
        sliders[s.name] = (p[:3] - env0, np.array(_xyzw(_matrix_quat(frame))))
    sb = None
    if spec.plastic is not None:
        live = _SET.get(spec.name)
        sb = None if live is None else np.asarray(live[0], dtype=float)
    return _state(spec, pts, quats, bodies, lin[idx].mean(0), ang[idx].mean(0), fixtures, sliders, sb)


def _rows_tensor(asset, rows):
    import torch

    return torch.tensor(rows, dtype=torch.float32, device=asset.device)


def _write_laid(environment, name: str) -> None:
    """Put one rope back as laid in every env: root at its default pose plus the env origin, every joint at 0, no root
    or joint velocity. The same writes as an Isaac Lab articulation reset, with joint position 0 (the laid shape)."""
    base = environment.unwrapped
    asset = base.scene[name]
    data = asset.data
    pose = getattr(data, "default_root_pose", None)
    if pose is None:
        pose = getattr(data, "default_root_state", None)
    if pose is None:
        raise AttributeError(f"ropekit: {name} has neither default_root_pose nor default_root_state")
    pose = mechkit._to_numpy(pose)
    if pose.ndim != 2 or pose.shape[1] < 7:
        raise ValueError(f"ropekit: {name} default root pose has shape {pose.shape}, expected (envs, 7 or 13)")
    envs = pose.shape[0]
    origins = mechkit._to_numpy(base.scene.env_origins)
    if origins.shape[0] < envs:
        raise ValueError(f"ropekit: {envs} root poses but {origins.shape[0]} env origins")
    root = pose[:, :7].copy()
    root[:, :3] += origins[:envs, :3]
    joints = len(asset.joint_names)
    write_pose = getattr(asset, "write_root_pose_to_sim_index", None) or asset.write_root_pose_to_sim
    write_vel = getattr(asset, "write_root_velocity_to_sim_index", None) or asset.write_root_velocity_to_sim
    pos = getattr(asset, "write_joint_position_to_sim_index", None) or asset.write_joint_position_to_sim
    vel = getattr(asset, "write_joint_velocity_to_sim_index", None) or asset.write_joint_velocity_to_sim
    write_pose(root_pose=_rows_tensor(asset, [[float(v) for v in row] for row in root]))
    write_vel(root_velocity=_rows_tensor(asset, [[0.0] * 6 for _ in range(envs)]))
    zero = _rows_tensor(asset, [[0.0] * joints for _ in range(envs)])
    pos(position=zero)
    vel(velocity=zero)


def _write_slider_start(environment, name: str) -> None:
    """Put a slider back at its start pose (default root pose plus the env origin), at rest, in every env."""
    base = environment.unwrapped
    asset = base.scene[name]
    pose = getattr(asset.data, "default_root_pose", None)
    if pose is None:
        pose = getattr(asset.data, "default_root_state", None)
    if pose is None:
        raise AttributeError(f"ropekit: slider {name} has neither default_root_pose nor default_root_state")
    pose = mechkit._to_numpy(pose)
    envs = pose.shape[0]
    root = pose[:, :7].copy()
    root[:, :3] += mechkit._to_numpy(base.scene.env_origins)[:envs, :3]
    write_pose = getattr(asset, "write_root_pose_to_sim_index", None) or asset.write_root_pose_to_sim
    write_vel = getattr(asset, "write_root_velocity_to_sim_index", None) or asset.write_root_velocity_to_sim
    write_pose(root_pose=_rows_tensor(asset, [[float(v) for v in row] for row in root]))
    write_vel(root_velocity=_rows_tensor(asset, [[0.0] * 6 for _ in range(envs)]))


def _reset_ropes(environment) -> None:
    """mechkit on_reset hook: write every rope in this env's scene back as laid, its plastic set back to the laid
    shape (targets 0), then its sliders back at their start. An Arena reset moves an articulation by its root only,
    so without this a rope keeps the last trial's bent shape."""
    scene = environment.unwrapped.scene
    live = set(scene.articulations)
    rigid = set(getattr(scene, "rigid_objects", ()))
    for name in list(_ROPES):
        if name in live:
            _write_laid(environment, name)
            spec = _ROPES[name]
            if spec.plastic is not None:
                asset = scene[name]
                envs = mechkit._to_numpy(asset.data.joint_pos).shape[0]
                _write_targets(asset, np.zeros((envs, len(asset.joint_names))))
                _SET[name] = np.zeros((envs, spec.segments - 1, 2))
            for s in spec.sliders:
                if s.name in rigid:
                    _write_slider_start(environment, s.name)


# -- run time: plastic set ------------------------------------------------------------------------------------------------


def _dof_map(names, joints: int) -> np.ndarray:
    """(joints, 2) indices into the articulation's DOFs: the rotY and rotZ DOF of each bend joint 1 .. joints, in
    order. Names that carry ``bend_<i>`` group by i (two DOFs each, in the order listed, taken as rotY then rotZ);
    otherwise exactly 2 x joints DOFs are taken in order. Anything else raises."""
    import re

    names = list(names)
    groups: dict[int, list[int]] = {}
    for k, n in enumerate(names):
        m = re.search(r"bend_(\d+)(?!\d)", str(n))
        if m:
            groups.setdefault(int(m.group(1)), []).append(k)
    if groups:
        if sorted(groups) != list(range(1, joints + 1)) or any(len(v) != 2 for v in groups.values()):
            raise ValueError(f"ropekit: bend DOFs do not pair up as 2 per joint 1..{joints}: {names}")
        return np.array([groups[i] for i in range(1, joints + 1)], dtype=int)
    if len(names) == 2 * joints:
        return np.arange(2 * joints, dtype=int).reshape(joints, 2)
    raise ValueError(f"ropekit: cannot map {len(names)} DOFs {names} onto {joints} bend joints")


def _write_targets(asset, rows) -> None:
    """Position targets (envs, dofs) for every DOF of the articulation, as mechkit writes a spring rest."""
    rows = np.asarray(rows, dtype=float)
    v = _rows_tensor(asset, [[float(c) for c in row] for row in rows])
    ids = list(range(rows.shape[1]))
    cmd = getattr(getattr(asset, "actuators", None), "target_command", None)
    if cmd is not None and hasattr(cmd, "set_position_index"):
        cmd.set_position_index(value=v, joint_ids=ids)
    else:
        asset.set_joint_position_target(v, joint_ids=ids)


def _plastic_step(environment) -> None:
    """mechkit on_step hook (after every control step): for every plastic rope, move each joint's set by the yield
    rule and write the new drive targets when any changed."""
    if environment is None:
        return
    scene = environment.unwrapped.scene
    live = set(scene.articulations)
    for name, spec in list(_ROPES.items()):
        if spec.plastic is None or name not in live:
            continue
        asset = scene[name]
        q = mechkit._to_numpy(asset.data.joint_pos)
        idx = _dof_map(asset.joint_names, spec.segments - 1)
        bend = q[:, idx]  # (envs, joints, 2)
        old = _SET.get(name)
        if old is None or old.shape != bend.shape:
            old = np.zeros_like(bend)
        new = plastic_update(bend, old, spec.plastic.yield_angle, spec.max_bend)
        if not np.array_equal(new, old):
            rows = np.zeros_like(q)
            rows[:, idx] = new
            _write_targets(asset, rows)
        _SET[name] = new


# -- registering with yam_arena.scene through mechkit's hook ------------------------------------------------------------


def _patch_scene(scene) -> None:
    """Route Rope specs to ropekit and their names to RopeState; everything else goes on unchanged."""
    if getattr(scene, "_ropekit_patched", False):
        return
    plain_object, plain_states = scene.task_object, scene.object_states

    def task_object(spec):
        if isinstance(spec, Rope):
            return _arena_object(spec)
        return plain_object(spec)

    def object_states(environment, names):
        ropes = [n for n in names if n in _ROPES]
        if not ropes:
            return plain_states(environment, names)
        rest = [n for n in names if n not in _ROPES]
        out = dict(plain_states(environment, rest)) if rest else {}
        out.update({n: _rope_state(environment, _ROPES[n]) for n in ropes})
        return {n: out[n] for n in names}

    scene.task_object, scene.object_states = task_object, object_states
    scene._ropekit_patched = True


def _install() -> None:
    """Patch yam_arena.scene now if it is loaded, else chain onto mechkit's pending import hook for it. Raises when
    neither is possible, rather than leaving ropes unregistered."""
    scene = sys.modules.get("yam_arena.scene")
    if scene is not None:
        _patch_scene(scene)
        return
    finder_cls = getattr(mechkit, "_AfterImport", None)
    targets = getattr(finder_cls, "TARGETS", None)
    if not isinstance(targets, dict) or "yam_arena.scene" not in targets:
        raise ImportError("ropekit: this mechkit has no yam_arena.scene import hook to chain onto; use a matching "
                          "mechkit.py")
    waiting = [f for f in sys.meta_path if isinstance(f, finder_cls) and "yam_arena.scene" in getattr(f, "_pending", ())]
    if not waiting:
        raise ImportError("ropekit: mechkit's import hook is not waiting for yam_arena.scene; import ropekit right "
                          "after mechkit, before the simulator loads")
    current = targets["yam_arena.scene"]
    if getattr(current, "_ropekit_chain", False):
        return

    def chained(module) -> None:
        current(module)
        _patch_scene(module)

    chained._ropekit_chain = True
    targets["yam_arena.scene"] = chained


_install()
if not any(getattr(f, "__qualname__", "") == "_reset_ropes" and getattr(f, "__module__", "") == __name__
           for f in mechkit._RESET_HOOKS):
    mechkit.on_reset(_reset_ropes)
if not any(getattr(f, "__qualname__", "") == "_plastic_step" and getattr(f, "__module__", "") == __name__
           for f in mechkit._STEP_HOOKS):
    mechkit.on_step(_plastic_step)
