# -- small pure helpers --------------------------------------------------------------------------------------------------


def _num(what: str, value, low: float | None = None, high: float | None = None, low_open: bool = False) -> float:
    if isinstance(value, bool):
        raise ValueError(f"{what} must be a number, got {value!r}")
    try:
        v = float(value)
    except (TypeError, ValueError):
        raise ValueError(f"{what} must be a number, got {value!r}") from None
    if not math.isfinite(v):
        raise ValueError(f"{what} must be finite, got {value!r}")
    if low is not None and (v <= low if low_open else v < low):
        raise ValueError(f"{what} must be {'>' if low_open else '>='} {low}, got {v}")
    if high is not None and v > high:
        raise ValueError(f"{what} must be <= {high}, got {v}")
    return v


def _floats(seq) -> tuple[float, ...]:
    return tuple(float(c) for c in seq)


def _quat_matrix(q_wxyz) -> np.ndarray:
    return mechkit._quat_wxyz_matrix(q_wxyz)


def _matrix_quat(r) -> tuple[float, float, float, float]:
    """(w, x, y, z) of a proper rotation matrix, w >= 0, as plain floats."""
    m = np.asarray(r, dtype=float)
    t = m[0, 0] + m[1, 1] + m[2, 2]
    if t > 0:
        s = math.sqrt(t + 1.0) * 2
        q = (0.25 * s, (m[2, 1] - m[1, 2]) / s, (m[0, 2] - m[2, 0]) / s, (m[1, 0] - m[0, 1]) / s)
    elif m[0, 0] > m[1, 1] and m[0, 0] > m[2, 2]:
        s = math.sqrt(1.0 + m[0, 0] - m[1, 1] - m[2, 2]) * 2
        q = ((m[2, 1] - m[1, 2]) / s, 0.25 * s, (m[0, 1] + m[1, 0]) / s, (m[0, 2] + m[2, 0]) / s)
    elif m[1, 1] > m[2, 2]:
        s = math.sqrt(1.0 + m[1, 1] - m[0, 0] - m[2, 2]) * 2
        q = ((m[0, 2] - m[2, 0]) / s, (m[0, 1] + m[1, 0]) / s, 0.25 * s, (m[1, 2] + m[2, 1]) / s)
    else:
        s = math.sqrt(1.0 + m[2, 2] - m[0, 0] - m[1, 1]) * 2
        q = ((m[1, 0] - m[0, 1]) / s, (m[0, 2] + m[2, 0]) / s, (m[1, 2] + m[2, 1]) / s, 0.25 * s)
    q = np.array(q, dtype=float)
    q /= np.linalg.norm(q)
    if q[0] < 0:
        q = -q
    return tuple(float(c) for c in q)


def _xyzw(q_wxyz) -> tuple[float, float, float, float]:
    w, x, y, z = q_wxyz
    return (float(x), float(y), float(z), float(w))


def _frame(d) -> np.ndarray:
    """Rotation whose x axis is d and whose z axis is as close to world up as possible (a lying segment has a flat
    face down)."""
    x = np.asarray(d, dtype=float)
    x = x / np.linalg.norm(x)
    ref = np.array([0.0, 0.0, 1.0]) if abs(x[2]) < 0.99 else np.array([1.0, 0.0, 0.0])
    y = np.cross(ref, x)
    y /= np.linalg.norm(y)
    z = np.cross(x, y)
    return np.column_stack([x, y, z])


def polyline_length(points) -> float:
    p = np.asarray(points, dtype=float).reshape(-1, 3)
    return float(np.linalg.norm(np.diff(p, axis=0), axis=1).sum())


def _path(points) -> np.ndarray:
    try:
        p = np.asarray(points, dtype=float)
    except (TypeError, ValueError):
        raise ValueError(f"rope path must be a list of (x, y, z) points, got {points!r}") from None
    if p.ndim != 2 or p.shape[1] != 3 or len(p) < 2:
        raise ValueError("rope path must be at least two (x, y, z) points")
    if not np.isfinite(p).all():
        raise ValueError("rope path points must be finite")
    if (np.linalg.norm(np.diff(p, axis=0), axis=1) < 1e-9).any():
        raise ValueError("rope path repeats a point")
    return p


# -- laying out the segments, pure NumPy ---------------------------------------------------------------------------------


@dataclass(frozen=True)
class Layout:
    """The laid rope: ``centres`` (n, 3), ``rots`` (n, 3, 3) segment frames (x along the rope, start to end),
    ``knots`` (n + 1, 3) segment ends (start tip, joints, end tip), ``seg_len``, and ``overshoot``: how far past the
    path's last point the end tip had to be extended along the last leg (chords cut corners, so a rope as long as the
    path reaches slightly past it)."""

    centres: np.ndarray
    rots: np.ndarray
    knots: np.ndarray
    seg_len: float
    overshoot: float

    @property
    def n(self) -> int:
        return len(self.centres)

    @property
    def length(self) -> float:
        return self.n * self.seg_len


def _next_knot(p: np.ndarray, k: int, t: float, c: np.ndarray, L: float) -> tuple[int, float, np.ndarray, float]:
    """Walk the polyline from (segment k, parameter t) to the first point at distance L from c. Returns the new
    (k, t, point, overshoot); past the last point it extends the last leg."""
    last = len(p) - 2
    for kk in range(k, last + 1):
        a, e = p[kk], p[kk + 1] - p[kk]
        f = a - c
        A, B, C = float(e @ e), 2.0 * float(f @ e), float(f @ f) - L * L
        disc = B * B - 4 * A * C
        if disc < 0:
            continue
        lo = t if kk == k else 0.0
        hi = math.inf if kk == last else 1.0
        roots = sorted(((-B - math.sqrt(disc)) / (2 * A), (-B + math.sqrt(disc)) / (2 * A)))
        for u in roots:
            if lo - 1e-12 <= u <= hi:
                over = max(0.0, (u - 1.0) * math.sqrt(A)) if kk == last else 0.0
                return kk, u, a + u * e, over
    raise ValueError("rope path: could not lay a segment (path folds back within one segment)")


def segment_layout(path, segment: float = SEGMENT, length: float | None = None) -> Layout:
    """Lay n equal chords along the polyline ``path`` from its first point. ``length`` defaults to the path's length;
    n = round(length / segment) (at least 2) and the chord length is length / n. Each chord's ends lie on the path, so
    corners are cut; the end tip may run past the path's end along its last leg by ``overshoot`` (refused when more
    than one segment)."""
    p = _path(path)
    total = polyline_length(p) if length is None else _num("rope length", length, 0.0, low_open=True)
    seg = _num("rope segment", segment, 0.0, low_open=True)
    n = max(2, int(round(total / seg)))
    if n > MAX_SEGMENTS:
        raise ValueError(f"rope: {n} segments, over the {MAX_SEGMENTS} limit; use longer segments or a shorter rope")
    L = total / n
    knots, k, t, c, over = [p[0].copy()], 0, 0.0, p[0].copy(), 0.0
    for _ in range(n):
        k, t, c, over = _next_knot(p, k, t, c, L)
        knots.append(np.asarray(c, dtype=float))
    if over > L + 1e-9:
        raise ValueError(f"rope path is {over:.4f} m too short for a {total:.4f} m rope (more than one segment); "
                         "lengthen the path or give a shorter length")
    knots = np.array(knots)
    dirs = np.diff(knots, axis=0)
    centres = (knots[:-1] + knots[1:]) / 2
    rots = np.array([_frame(d) for d in dirs])
    return Layout(centres, rots, knots, float(L), float(over))


@dataclass(frozen=True)
class JointFrame:
    """One bend joint between segment i - 1 (body0) and segment i (body1): local positions and (w, x, y, z) local
    rotations, all plain floats, and the laid bend angle (rad) between the two segments."""

    index: int
    pos0: tuple[float, float, float]
    rot0: tuple[float, float, float, float]
    pos1: tuple[float, float, float]
    rot1: tuple[float, float, float, float]
    bend: float


def joint_frames(layout: Layout) -> list[JointFrame]:
    """Frames of joints 1 .. n - 1. The joint sits at the shared knot; its frame is segment i's frame, written in
    segment i - 1 as R(i-1)^T R(i), so joint position 0 is the laid shape and twist about the child's x axis is the
    locked rotX."""
    L = layout.seg_len
    out = []
    for i in range(1, layout.n):
        rel = layout.rots[i - 1].T @ layout.rots[i]
        cosb = float(np.clip(layout.rots[i - 1][:, 0] @ layout.rots[i][:, 0], -1.0, 1.0))
        out.append(JointFrame(i, (L / 2, 0.0, 0.0), _matrix_quat(rel), (-L / 2, 0.0, 0.0), IDENT, math.acos(cosb)))
    return out


def _rotvec_matrix(v) -> np.ndarray:
    """Rotation matrix of a rotation vector (axis x angle, rad)."""
    v = np.asarray(v, dtype=float)
    th = float(np.linalg.norm(v))
    if th < 1e-12:
        return np.eye(3)
    k = v / th
    K = np.array([[0.0, -k[2], k[1]], [k[2], 0.0, -k[0]], [-k[1], k[0], 0.0]])
    return np.eye(3) + math.sin(th) * K + (1 - math.cos(th)) * (K @ K)


def _seg_index(s: float, seg_len: float, n: int) -> int:
    """Index of the segment containing arclength ``s`` (a point on a joint belongs to the segment starting there;
    a hair under a joint from rounding counts as on it)."""
    return max(0, min(int(math.floor(s / seg_len + 1e-9)), n - 1))


def _arc_frame(lay: Layout, s: float) -> tuple[int, np.ndarray, np.ndarray]:
    """(segment index, segment rotation, point on the segment's axis) at arclength ``s`` of the laid rope. A point on
    a joint belongs to the segment that starts there."""
    L = lay.seg_len
    i = _seg_index(s, L, lay.n)
    return i, lay.rots[i].copy(), lay.knots[i] + (s - i * L) * lay.rots[i][:, 0]


def _chain_knots(r0, c0, rels, bends, seg_len: float) -> np.ndarray:
    """Knots (n + 1, 3) of a chain whose segment 0 has rotation ``r0`` and centre ``c0`` and whose joint i turns
    segment i by laid relative rotation ``rels[i - 1]`` followed by the bend rotation vector (0, a, b) in the joint
    frame, ``bends[i - 1]`` = (a, b) (rad, about the joint's y then z axis; exact for a bend about one axis)."""
    rot = np.asarray(r0, dtype=float)
    knots = [np.asarray(c0, dtype=float) - rot[:, 0] * seg_len / 2]
    knots.append(knots[0] + rot[:, 0] * seg_len)
    for rel, b in zip(rels, bends):
        b = np.asarray(b, dtype=float).reshape(-1)
        v = np.zeros(3)
        v[1:1 + min(2, len(b))] = b[:2]
        rot = rot @ rel @ _rotvec_matrix(v)
        knots.append(knots[-1] + rot[:, 0] * seg_len)
    return np.array(knots)


def prism_points(seg_len: float, radius: float, sides: int) -> np.ndarray:
    """Collider points of one segment, along x: an n-gon prism with its flats at ``radius`` (one flat facing -z) and
    chamfered ends that reach about as far as a round cap (inner rings at +-(L/2 - 0.3 r), outer rings at
    +-(L/2 + 0.6 r) on 0.55 x the vertex radius), as the accepted cable kits use."""
    n = int(sides)
    rv = radius / math.cos(math.pi / n)
    pts = []
    for x, rr in ((seg_len / 2 - 0.3 * radius, rv), (seg_len / 2 + 0.6 * radius, 0.55 * rv)):
        for sx in (-x, x):
            for k in range(n):
                a = 2 * math.pi * (k + 0.5) / n - math.pi / 2
                pts.append((sx, rr * math.cos(a), rr * math.sin(a)))
    return np.array(pts, dtype=float)


def segment_collider(seg_len: float, radius: float, sides: int) -> Shape:
    """The hidden prism collider of one segment as a mechkit Shape (kind "mesh", form "hull", invisible, contact
    offset 2 mm). Its ``at`` is the centre of its bounding box, off the axis for an odd number of sides."""
    s = mechkit.hull((0.0, 0.0, 0.0), prism_points(seg_len, radius, sides), contact=CONTACT)
    return dataclasses.replace(s, visible=False)


def _seg_seg_distance(p0, p1, q0, q1) -> float:
    """Least distance between segments p0-p1 and q0-q1."""
    d1, d2, r = p1 - p0, q1 - q0, p0 - q0
    a, e, f = float(d1 @ d1), float(d2 @ d2), float(d2 @ r)
    if a <= 1e-18 and e <= 1e-18:
        return float(np.linalg.norm(r))
    if a <= 1e-18:
        return float(np.linalg.norm(p0 - (q0 + d2 * float(np.clip(f / e, 0.0, 1.0)))))
    if e <= 1e-18:
        return float(np.linalg.norm(p0 + d1 * float(np.clip(-float(d1 @ r) / a, 0.0, 1.0)) - q0))
    c, b = float(d1 @ r), float(d1 @ d2)
    den = a * e - b * b
    s = float(np.clip((b * f - c * e) / den, 0.0, 1.0)) if den > 1e-18 else 0.0
    t = (b * s + f) / e
    if t < 0.0:
        t, s = 0.0, float(np.clip(-c / a, 0.0, 1.0))
    elif t > 1.0:
        t, s = 1.0, float(np.clip((b - c) / a, 0.0, 1.0))
    return float(np.linalg.norm((p0 + d1 * s) - (q0 + d2 * t)))


def _self_clearance(layout: Layout, radius: float) -> tuple[float, tuple[int, int] | None]:
    """Least surface gap (m) between round segments at least two apart in the laid shape, and the pair."""
    best, pair = math.inf, None
    k, c, L = layout.knots, layout.centres, layout.seg_len
    for i in range(layout.n):
        for j in range(i + 2, layout.n):
            if np.linalg.norm(c[i] - c[j]) > L + 2 * radius + best:
                continue
            g = _seg_seg_distance(k[i], k[i + 1], k[j], k[j + 1]) - 2 * radius
            if g < best:
                best, pair = g, (i, j)
    return best, pair


# -- polylines on the table, plain floats --------------------------------------------------------------------------------


def _pts(rows) -> tuple[tuple[float, float, float], ...]:
    return tuple((float(x), float(y), float(z)) for x, y, z in rows)


def straight(start_xy, yaw: float, length: float, z: float):
    """Two points: from ``start_xy`` along ``yaw`` (rad about z, 0 = +x) for ``length`` at axis height ``z``."""
    x, y = _floats(start_xy)
    L, yaw, z = _num("length", length, 0.0, low_open=True), _num("yaw", yaw), _num("z", z)
    return _pts([(x, y, z), (x + L * math.cos(yaw), y + L * math.sin(yaw), z)])


def fillet(points, radius: float, step_deg: float = 10.0):
    """Round every interior corner of a polyline with an arc of ``radius`` (m), as plain-float points. A chord laid
    across a sharp corner bends one joint by most of the corner angle; with a fillet each joint bends about
    segment / radius rad. Raises when a fillet does not fit on its legs (each leg shared by two corners gives each at
    most half its length)."""
    p = _path(points)
    rho = _num("fillet radius", radius, 0.0)
    step = math.radians(_num("step_deg", step_deg, 1.0, 30.0))
    if rho == 0.0 or len(p) < 3:
        return _pts(p)
    legs = np.linalg.norm(np.diff(p, axis=0), axis=1)
    out = [p[0]]
    for i in range(1, len(p) - 1):
        u1 = (p[i] - p[i - 1]) / legs[i - 1]
        u2 = (p[i + 1] - p[i]) / legs[i]
        phi = math.acos(float(np.clip(u1 @ u2, -1.0, 1.0)))
        if phi < 1e-6:
            out.append(p[i])
            continue
        if phi > math.pi - 1e-6:
            raise ValueError(f"fillet: the path doubles back at point {i}")
        t = rho * math.tan(phi / 2)
        room1 = legs[i - 1] if i == 1 else legs[i - 1] / 2
        room2 = legs[i] if i == len(p) - 2 else legs[i] / 2
        if t > min(room1, room2) + 1e-12:
            raise ValueError(f"fillet: a {rho:.4f} m fillet needs {t:.4f} m of each leg at point {i}; use a smaller "
                             "radius or longer legs")
        a = p[i] - u1 * t
        nrm = u2 - u1 * float(u1 @ u2)
        nrm /= np.linalg.norm(nrm)
        centre = a + nrm * rho
        m = max(1, int(math.ceil(phi / step)))
        v0 = a - centre
        for k in range(m + 1):
            th = phi * k / m
            out.append(centre + v0 * math.cos(th) + u1 * rho * math.sin(th))
    out.append(p[-1])
    keep = [out[0]]
    for q in out[1:]:
        if np.linalg.norm(np.asarray(q) - np.asarray(keep[-1])) > 1e-9:
            keep.append(q)
    return _pts(keep)


def _turn_sign(turn: str) -> float:
    if turn not in ("left", "right"):
        raise ValueError(f"turn must be left or right, got {turn!r}")
    return 1.0 if turn == "left" else -1.0


def l_path(start_xy, yaw: float, leg1: float, leg2: float, z: float, turn: str = "left", corner: float = 0.03):
    """An L: ``leg1`` along ``yaw``, a right-angle turn (left = counter-clockwise seen from above) rounded with a
    ``corner`` radius (0 for a sharp corner, which the rope may refuse), then ``leg2``."""
    x, y = _floats(start_xy)
    a, b = _num("leg1", leg1, 0.0, low_open=True), _num("leg2", leg2, 0.0, low_open=True)
    yaw, z, s = _num("yaw", yaw), _num("z", z), _turn_sign(turn)
    cx, cy = x + a * math.cos(yaw), y + a * math.sin(yaw)
    y2 = yaw + s * math.pi / 2
    return fillet([(x, y, z), (cx, cy, z), (cx + b * math.cos(y2), cy + b * math.sin(y2), z)], corner)


def u_path(start_xy, yaw: float, leg: float, width: float, z: float, turn: str = "left", back: float | None = None,
           corner: float | None = None):
    """A U: ``leg`` along ``yaw``, a turn, ``width`` across, the same turn again, then ``back`` (default ``leg``)
    returning parallel to the first leg. ``width`` is axis to axis: at least 2 x radius plus a gap. ``corner`` rounds
    both turns (default: half the width, a semicircular bend)."""
    x, y = _floats(start_xy)
    a, w = _num("leg", leg, 0.0, low_open=True), _num("width", width, 0.0, low_open=True)
    b = a if back is None else _num("back", back, 0.0, low_open=True)
    yaw, z, s = _num("yaw", yaw), _num("z", z), _turn_sign(turn)
    d0 = np.array([math.cos(yaw), math.sin(yaw)])
    d1 = np.array([math.cos(yaw + s * math.pi / 2), math.sin(yaw + s * math.pi / 2)])
    p0 = np.array([x, y])
    p1 = p0 + a * d0
    p2 = p1 + w * d1
    p3 = p2 - b * d0
    rho = w / 2 if corner is None else _num("corner", corner, 0.0)
    return fillet([(*p, z) for p in (p0, p1, p2, p3)], rho)


def coil(centre_xy, inner: float, turns: float, pitch: float, z: float, start_angle: float = 0.0,
         direction: str = "left", lead_out: float = 0.0, step_deg: float = 10.0):
    """A flat spiral lying on the table (a coiled cable cannot overlap itself flat): radius grows from ``inner`` by
    ``pitch`` per turn (pitch at least 2 x radius plus a gap, axis to axis). ``direction`` left winds counter-clockwise
    seen from above, from the inside out. ``lead_out`` adds a straight tail along the last tangent."""
    cx, cy = _floats(centre_xy)
    r0 = _num("inner", inner, 0.0, low_open=True)
    n_turns, p = _num("turns", turns, 0.0, low_open=True), _num("pitch", pitch, 0.0, low_open=True)
    z, a0 = _num("z", z), _num("start_angle", start_angle)
    tail, step = _num("lead_out", lead_out, 0.0), math.radians(_num("step_deg", step_deg, 1.0, 30.0))
    s = _turn_sign(direction)
    span = 2 * math.pi * n_turns
    m = max(2, int(math.ceil(span / step)))
    rows = []
    for k in range(m + 1):
        th = span * k / m
        r = r0 + p * th / (2 * math.pi)
        rows.append((cx + r * math.cos(a0 + s * th), cy + r * math.sin(a0 + s * th), z))
    if tail > 0:
        d = np.subtract(rows[-1][:2], rows[-2][:2])
        d /= np.linalg.norm(d)
        rows.append((rows[-1][0] + tail * d[0], rows[-1][1] + tail * d[1], z))
    return _pts(rows)


