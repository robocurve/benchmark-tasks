"""ropekit: ropes, cords and cables for yam_arena task files, beside mechkit.

A rope is a chain of short rigid segments (about 2 cm) joined by D6 joints. Stretch and twist are locked; each joint
bends on two axes within +-max_bend, with a spring and damper that pull it back toward the shape it was laid in. The
whole rope, with any rigid end bodies (a plug, a ring, a hook, or any mechkit Shapes) welded to its ends, is ONE
articulation. The start can be anchored to the world (a cable leaving a wall box).

    import mechkit, ropekit
    from ropekit import Rope, plug, l_path, axis_height

    Z = axis_height(TOP, 0.004, plug())
    CABLE = Rope("cable", path=l_path((0.18, 0.12), yaw=0.0, leg1=0.20, leg2=0.15, z=Z, turn="right"),
                 radius=0.004, end_body=plug())
    OBJECTS = [CABLE, ...]

    def score(objects):
        s = objects["cable"]                   # a RopeState
        return 1.0 if s.end_distance("end", (0.30, -0.05, TOP + 0.01)) < 0.01 else 0.0

The start pose is laid along a polyline (``straight``, ``l_path``, ``u_path``, ``coil`` build one with plain floats).
The laid shape is the joints' zero. An Arena reset moves an articulation by its root only, so ropekit writes the laid
pose back on every reset (root at its default pose, every joint at 0, no velocity; a mechkit on_reset hook), and the
bend springs pull toward that shape (the "set" a real coiled cable keeps), not toward straight. Keep the springs soft (0.003 to 0.02 N m/rad) and table friction keeps whatever shape the robot leaves.

score() gets a ``RopeState``: every segment centre, every end frame (an end body's pose, or the bare tip), the nominal
and measured length, and helpers: ``sag``, ``passes_through`` (a ring), ``wrap_angle`` / ``round_post`` (a post),
``end_distance``. ``mock_state(rope)`` gives one for offline dry runs.

Registration: importing ropekit chains its scene patch onto mechkit's own import hook (mechkit._AfterImport.TARGETS),
or patches yam_arena.scene directly when it is already imported. There is no second import hook. Keep mechkit.py and
ropekit.py beside the task file.

Simulator parameters follow the accepted cable kits in the same simulator: D6 joints with transX/Y/Z and rotX locked
(LimitAPI low 1 > high -1), rotY/rotZ limited and driven, 32 position and 4 velocity solver iterations, max
depenetration velocity 1.0 m/s, linear damping 0.5, angular damping 2.0, armature 5e-6 per bend DOF, contact offset
2 mm, rest offset 0, self-collision on, the articulation root on segment 0, and an optional n-sided prism collider so a
straight rope cannot roll forever.

Limits (see GEOMETRY.md, "Ropes and cables"): radius under about 3 mm is untested; segment length must exceed the
diameter; a demo should grasp a rigid end body or work near an anchored point, never a bare segment it has to find.

Bodies partway along a rope (see ``Fixture`` and ``Slider``):

    TAG = Fixture("tag", sleeve(0.02, 0.004), at=0.25)          # welded to the segment at 25 cm
    BORE = slider_bore(0.003)                                   # rope collider radius + 1.5 mm
    CHIN = Slider("chin", slider_body(BORE, 0.015), at=0.40, bore=BORE)
    TUBE = Rope("tube", path=..., radius=0.003, fixtures=(TAG,), sliders=(CHIN,), end_body=plug())
    OBJECTS = [TUBE, *TUBE.slider_objects()]                    # a slider is its own rigid task object

    def score(objects):
        s = objects["tube"]
        return 1.0 if abs(s.slider_arclength("chin") - 0.20) < 0.02 and s.slider_on_rope("chin") else 0.0

Wire that keeps its bend (see ``Plastic``): ``Rope(..., plastic=copper_12awg())`` drives every bend joint to a target
that follows the bend once it passes a yield angle, so the wire springs back a little and keeps a large bend;
``RopeState.set_bends``, ``set_polyline()`` and ``set_turn()`` give the set shape to a scorer.

Assets: all geometry is procedural, generated by this file and mechkit.py; no third-party meshes or textures.
"""

